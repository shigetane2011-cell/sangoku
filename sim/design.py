    # 訊く、は呼び手が量0のときにも通すためで、値は使われない）。
    ally = ("味方" in target) or ("自分" in target)
    if (ally and what == "打撃") or (not ally and what == "回復"):
        return None
    key = (what, target)
    if key not in _UNPRICED:
        _UNPRICED.add(key)
        import sys as _sys
        print("！ 対象「{}」の{}係数が表に無い（既定で通す）".format(target, what),
              file=_sys.stderr)
    return None


