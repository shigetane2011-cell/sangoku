# ============================================================================
#
# **式を当てず、測った表をそのまま持つ**（TRAIT_PRICE と同じ理由）。一撃で
# 隊を消すと、削るだけでは奪えない「その隊の残りの出力」を丸ごと奪う。この
# 価値は damage_price の緩い冪では拾えず、実測で威力1500%超の大技7枚が
# 平均 +4.4 コスト点の安売りになっていた（盤面監査・tools/price_audit.py）。
