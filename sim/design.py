# 測りかた（§7.199 ⑩-a）: 頭を**値打ちのほぼ無い**「移動速度 +1%（N秒）」に置き換え、
# 待ち時間だけを振る。こうすると逐次の値がそのまま「遅れて始まった尻尾の値打ち」に
# なる（§7.199 ⑥の「逐次 ÷ 同時」は頭の値打ちに薄められていて、45秒で 0.52 と
# 甘く出ていた。本当は 0.27）。于禁の車体・尻尾は 攻撃力 +30%（20秒）／自分と右隣・
# 実カードの土台12 × 相手240組。
#
#   待ち（盤面の秒）   0     1.5    15     30     45
#   実測の掛け目     0.99  0.93   0.52   0.35   0.27
#   1/(1+待ち/16.5)  1.00  0.92   0.52   0.35   0.27
#
# 最小二乗で a = 16.5秒・二乗誤差 0.00003。5点すべて小数2桁まで合う。
#
# **測ったのは攻撃力バフの尻尾1種・車体1枚だけ。** 一撃や回復を「その後」に書く札を
# 作るときは、同じやりかたで当てはまりを測り直すこと。いま「→ その後」を持つのは
# 廖化〔老将〕と于禁〔毅重〕の2枚だけなので、外れても影響はその2枚に収まる。
AFTER_DELAY_A = 16.5


def after_f(wait: float) -> float:
    """遅れて始まる効果の掛け目（§7.200）。wait は**盤面の秒**。"""
    return 1.0 / (1.0 + max(wait, 0.0) / AFTER_DELAY_A)


# 恒久の強化（§7.235）の「残り時間の目安」。戦闘は90秒で、誘発が鳴るのは概ね中盤
# （味方の壊滅は初弾の中央値 43〜48秒・4割割れはそれより早い）。**仮の値**であって
# 測ったものではない — 恒久を使う札が増えたら、発動時刻を数えて置き直すこと。
PERM_SECS = 45.0


def mods_value(mods, target: str, fx: float) -> float:
    """状態効果の並び1本ぶんの値段（**段の重みを掛ける前**）。

    兵法の本体（`skill.mods`）と「→ その後」の後半（`after_mods`）が
    **同じ関数を通る**。別々に書くと、単価を直したとき片方だけ古いまま残る。
    """
    # 【§7.232】**効き先で引く。札の対象で引かない。**
    # `field._skill_mods` の符号規約は「敵対象の札でも**プラスの節は撃った本人だけ**に
    # 乗る」（`dst = (tgts if ally else [u]) if amt > 0 else …`）。値付けが札の対象で
    # 引いていたので、**敵後列の札に自分強化を付けると 3.16倍・前衛の主力なら 0.60倍**
    # で請求していた（趙雲〔長坂坡〕・傅僉〔守将〕・曹彰〔黄鬚〕）。
    # **行動阻害・ゲージ阻害・混乱は符号に関わらず敵だけ**なので、この振り替えをしない。
    ally = ("味方" in target) or ("自分" in target)

    def _eff(amt: float):
        """その節が実際に乗る先（対象文字列, 対象係数）。"""
        if not ally and amt > 0.0:
            return "自分", target_fx("自分")
        return target, fx

    v = 0.0
    for key, amt, secs in mods:
        if key == "stun":
            v += EFFECT_PRICE["stun"] * secs * fx
        elif key == "glock":
            v += EFFECT_PRICE["glock"] * secs * fx
        elif key in ("atk", "def"):
            v += EFFECT_PRICE[key] * abs(amt) * 100.0 * secs * _eff(amt)[1]
        elif key in ("perm_atk", "perm_def"):
            # 恒久の強化（§7.235）。**秒を持たない**ので、鳴ってから戦闘が終わるまでの
            # 残り時間で値付けする。ここを 0 のままにすると、また「値札の無い器」が
            # 生まれる（移動速度で踏んだ・§7.230）。
            v += (EFFECT_PRICE[key[5:]] * abs(amt) * 100.0 * PERM_SECS
                  * _eff(amt)[1])
        elif key in ("scut", "refl", "nrefl", "ncut", "null"):
            table = {"scut": TARGET_SCUT_PRICE, "refl": TARGET_REFL_PRICE,
                     "nrefl": TARGET_NREFL_PRICE,
                     "ncut": TARGET_NCUT_PRICE, "null": TARGET_NULL_PRICE}[key]
            tgt = _eff(amt)[0]          # 構えも同じ規約（いま敵対象の持ち手は0枚）
            base = next(iter(table.values()))
            for k, pv in table.items():
                if k in tgt or tgt in k:
                    base = pv
                    break
            if key == "null":     # 量ではなく回数（§7.152）。秒数は飽和曲線
                v += base * null_secs_f(secs) * null_count_f(amt)
            elif key == "scut":   # 量は線形・秒数は飽和曲線（§7.193）
                v += base * (abs(amt) * 100.0 / SCUT_AMT_REF) * scut_secs_f(secs)
            else:                 # refl・ncut は秒数を振っていないので線形のまま
                v += base * (abs(amt) * 100.0 * secs) / SCUT_BASE
        elif key == "chaos":
            v += EFFECT_PRICE["chaos"] * chaos_equiv(amt) * 100.0 * secs * fx
    return v


# 引き延ばし（§7.259）の単価。「掛かっている弱体を**元の長さ × N 倍**へ」1倍ぶん・
# 対象係数1あたりのコスト点。
#
# **測り方**: この器は新しく掛けない。伸ばすだけなので、値打ちは
# 「**伸びた秒数ぶんの、その弱体そのものの値段**」である。だから単価を新しく
# 測る必要はなく、**いまの名簿の弱体25本を、秒数だけ半分にして差を取る**と
# 「秒の値段」が出る。そこへ 0.5×元の長さ を掛けたのが1本ぶんの値打ち:
#
#   足止め（11本）  中央 0.352  最大 1.391（龐統・敵1列3秒）
#   混乱  （ 6本）  中央 0.459  最大 0.729（貂蝉・敵前衛14秒）
#   延焼  （ 8本）  中央 0.872  最大 1.431（周瑜・敵1列14秒）
#   三つまとめて    中央 0.496  平均 0.596  最大 1.431
#
# **何本ぶん請求するか**が唯一の仮定。この器は「味方が先に撒く編成でだけ働く」
# ので、**組んだ編成を前提に 2本ぶん**（中央 0.496 × 2 ≒ 1.0）で置く。
# 司馬昭の勢力バフ（§7.258）と同じ約束 —— **組んだ人でちょうど・組まない人は損**。
# 満額（最大 1.431 を何本も）で請求すると、§7.258 で踏んだとおり
# **ただ弱いだけの札**になる。
#
# **単位に注意。** 上の 0.496 は `effect_value` の差（＝段の重みまで掛かった後）で
# 測った量なので、単価もそこへ合わせて逆算してある。一度 `mods_value` の層で
# 0.819 と置いて踏んだ —— 段の重み（大技 0.479）がその後に掛かるので、
# 王平の請求が 1.00 のつもりで **0.194 にしかならなかった**。
#
#   大技・敵前衛・コスト5 で `effect_value` = 0.50（＝中央 0.496 の**1本ぶん**）
#
# **2本ぶんで作って、測ってから1本ぶんへ下げた。** 「組んだ編成なら2本は掛かって
# いるだろう」という見込みが実測に合わなかった。王平の前後比較（官渡30・12性格×20種）:
#
#   請求          撒き手のいない土台   撒き手のいる土台
#   0.99（2本）    -5.42%(±1.58)   -2.50%(±1.31)  ← 組んでも損
#   0.50（1本）    -3.33%(±1.43)   +0.83%(±1.18)  ← 組めば互角
#
# 大技は1戦に1回しか撃たず、しかも遅い。**その1回の時点で敵前衛に生きている弱体は
# 平均して1本**、というのが実測の言っていることである。司馬昭（§7.258）とまったく
# 同じ形で踏んだ —— **仮定した「届く量」が多すぎると、札はただ弱くなる。**
#
# **上限は器の側でも引いてある**（`field.STRETCH_CAP = 2.0`）。伸びる秒数は
# 元の長さに比例するので、長い弱体と組むと1枚で戦況が決まる量になる。
STRETCH_PRICE = 2.098

# 写し取り（§7.260）の単価。「次に味方が放つ決戦型を写す」1秒あたり・コスト点。
#
# **値打ちは「決戦型1発ぶん」で頭打ちになる。** 写せるのは1回だけなので、
# 窓をいくら長くしても2発にはならない。だから秒に比例させるのは
# **飽和するぶんを高く請求する**向き（＝安全側・一騎討ちの秒と同じ・§7.249）。
#
# 錨は**名簿の決戦型の効果予算**（1戦に1回撃つ札の値打ちそのもの）:
#
#   決戦型 8本  効果予算 中央 1.163  最大 1.517
#
# 35秒の窓で中央（1.163）を請求する。**写しは馬良自身の武力・知力で解ける**ので
# 打撃の写しは本家の4割ほどにしかならない（馬良 武力177/知力276 に対し
# 諸葛亮 457/660）。怖いのは能力に依らない器（バフ・足止め・混乱）のほうで、
# そちらは満額で写る —— **中央で請求して最大を許すのは、その差を見込んだ緩み**である。
#
# **この器の値打ちは「自分のデッキのいちばん強い決戦型」で決まる。**
# 馬良のコストでは決まらないので、**決戦型を新設したら馬良を測り直すこと**
# （落とし穴72 の例外側＝値札が追いつかない器）。
MIMIC_PRICE = 0.0281

# 上書き（§7.263）の掛け目。「すでに攻めが上がっている相手にだけ、弱体がもう N%
# 深く入る」——**当たる相手の割合**そのものが掛け目になる。
#
# **この器の値打ちは相手のデッキで決まる**（自分のデッキではない）。引き延ばし
# （§7.259）や勢力の号令（§7.258）は「組んだ編成でちょうど」だったが、上書きは
# 組みようがない —— 相手が攻撃バフを使わなければ、何をしても素の弱体1本で終わる。
# だから**実測の割合をそのまま掛ける**のが唯一の置き方になる。
#
# **測り方**: 文聘を実土台へ入れて官渡30戦を回し、兵法が撃たれた各回で
# 「敵前衛のうち攻撃倍率が 1.0 を超えていた隊の割合」を数えた（197発）:
#
#   平均 42.8%  中央 33.3%  1体も上がっていなかった発 41.6%
#
# **中央値（1/3）で置く。** 値付けの要約は中央値に揃えてある（handoff §1）。
# ゼロの発が4割あって分布が片寄っているので、平均で置くと「当たらない試合」に
# 払わせすぎる。
#
# **層に注意。** この掛け目は素の攻撃力弱体の単価へ直に掛ける（`effect_value` の
# 中・段の重みより前）。素の節と同じ層に置くので、段の重みは両方へ等しく掛かり、
# §7.259 で踏んだ層の取り違えが起きない。
OVERWRITE_RATE = 1.0 / 3.0


def effect_value(skill, target: str = "", gauge_cost: float = 100.0,
                 gauge_init: float = 0.0, kisei: float = 1.0,
                 cost: float = F.BASE_COST, typ: str = F.INF,
                 tilt: str = "中庸") -> float:
    """兵法1つの値段（**1枚のコスト点**）。`field.Skill` と対象文を受ける。

    実カード36種で当てた式。絶対誤差は平均 0.062・最大 0.298 コスト点。

    **移動速度とゲージ付与には値段が付かない。** どちらも実測 0.00 だった。
    理由が違うので、まとめて 0 にはできない。

    - 移動速度: 接敵が終わったあとに撃っても動いている相手がいない。初期ゲージ0
      なら 0.00、初期ゲージ100（開幕発動）なら 1.60 と、**発動時刻の崖**である。
    - ゲージ付与: 味方の消費ゲージに届かなければ1回も増えない。3秒ぶんで 0.00、
      6秒ぶんで 0.05、12秒ぶんで 0.93 と**閾値をまたぐ段**になっている。

    どちらも「量」ではなく「いつ・いくつ閾値を越えたか」で決まるので、線形の
    単価を置くと嘘になる。値段を付けたければ発動時刻を設計の入力に入れること。
    """
    n = target_n(target)
    # 【測って却下】「打撃は武力に比例するのだから、撃つ側のコストで値段も伸ばす
    # べき」と考えて補正を入れかけたが、**計器を3つ作ったら符号が揃わなかった。**
    #
    #   撃つ側のコスト        2      3      5      8     10
    #   同じコストどうしの編成  1.000  1.000  1.000  1.000  1.000
    #   総コスト30を固定      0.415  0.627  1.000  0.900  0.892
    #   武力の比（予想）      0.751  0.834  1.000  1.249  1.415
    #
    # 同コスト編成では**完全に一定**（相手の兵力も同じ割合で増えるので、残存率の差が
    # 動かない）。総コスト固定ではコスト5を頂点に両側へ落ちる。予想は単調増加。
    # §13「パラメータを振って符号が変わらないものだけを結論に使う」に従い、補正は
    # 入れない。cost 引数は残してあるが値段には効かない。
    #
    # 【未解決・v0.6】ただし**高コストでは傾きの残差がコストとともに開く**。上限に
    # 一度も当たらない条件で測った智将・勇将の残差:
    #
    #   コスト     威力500%        威力1000%       威力1500%
    #     5     +0.067/-0.008  -0.061/-0.063  （上限に当たる）
    #    10     +0.106/-0.156  +0.217/-0.136  +0.239/-0.180
    #
    # コスト5では威力を振っても ±0.07 に収まるのに、コスト10では威力に比例して
    # 開く。`tilt_coef` がコストに依らないので、高コスト札では傾きの補正が効き
    # 足りていない。上の「補正を入れない」判断は**値段の水準**についてのもので、
    # こちらは**傾きの差**なので別の話である。直すには tilt_coef にコスト依存を
    # 入れることになり、上の3計器と正面からぶつかるので、測り直してから決める。
    # 打撃と回復だけが兵法の係数（武力・知力の配合）に乗る。状態効果は率なので乗らない。
    tc = tilt_coef(skill.kind, typ, tilt)
    fx = target_fx(target)
    v = 0.0
    # 威力の幅（§7.67）は中央値で払う。盤面の平均も中央値（一様乱数）で、
    # damage_price の冪は 0.95 とほぼ線形なので凸性のずれは 1% 未満。
    power_hi = getattr(skill, "power_hi", 0.0)
    if power_hi > skill.power:
        skill = skill.__class__(**{**skill.__dict__,
                                   "power": (skill.power + power_hi) / 2.0})
    # 知力比の傾き（§7.67）: 相手の知力はプールの平均（≒中庸）と見なし、撃ち手の
    # 傾きぶんだけ効き目が伸びる。弱体（下の wits_mods）では値段側に掛けるが、
    # 吸収（§7.247）は**打撃そのものが伸びる**器なので、威力へ掛けて下流
    # （damage_price・吸収の戻り・討ち取りの割増）へ一度で通す。
    wk = tilt_k(tilt) ** F.WITS_MOD
    if getattr(skill, "drain_wits", False):
        skill = skill.__class__(**{**skill.__dict__, "power": skill.power * wk})
    if skill.dur > 0.0 and skill.power > 0.0:
        # 継続ダメージ（§7.180）: **同じ総量の1発として払う**。§7.179 で測ったとおり
        # 盤面へ入る量は同じ総量の1発と変わらず（固定の的では与ダメが完全に一致）、
        # 違うのは入る時刻だけ（同総量で 13秒 −0.0008／65秒 −0.0089 コスト点相当）。
        # 旧 `EFFECT_PRICE["dot"]` は**縮尺後の秒数**に単価を掛けるので、同じ総量の
        # 1発の **2.0倍** を請求していた（縮尺 ×1.5 が片側だけ値段に入るうえ、
        # §7.147 の「実デッキ未測なので控えめ」の ×1.3 が乗っていた）。
        v += damage_price(dot_equiv_power(skill) * tc) * target_dmg_f(target)
    elif skill.power > 0.0:
        v += damage_price(skill.power * tc) * target_dmg_f(target)
    v += EFFECT_PRICE["heal"] * skill.heal * tc * target_heal_f(target) \
        * HEAL_TYPE_MULT.get(typ, 1.0)
    # 吸収（§7.247）: 打撃で奪った兵の DRAIN_SHARE ぶんが撃ち手へ戻る。
    # **戻りは「自分への回復」として払う。** 敵側の対象係数で請求すると抜け道が
    # できる — 打撃の係数は 敵全体 0.992 が 敵1体（正面）1.286 より**安い**ので、
    # 対象を広げるほど同じ戻りが安く買えてしまう（総ダメージは対象数で割るので
    # 戻る量は対象を広げても変わらない）。戻る先は常に撃ち手1隊なので、
    # target_heal_f("自分") で固定して敵の対象文から切り離す。
    # 一騎討ち（§7.249）: 敵1体を N秒 二人だけの盤面へ引きずり出す。
    # 対象係数は状態効果と同じ `fx`（止める器なので打撃の係数ではない）。
    duel = getattr(skill, "duel", 0.0)
    if duel > 0.0:
        v += EFFECT_PRICE["duel"] * duel * fx
    # 引き延ばし（§7.259）。**倍率−1 に比例**する（1.5倍なら 0.5 ぶん）。
    # 伸びる秒数が元の長さに比例するので、値打ちも比例で置ける（STRETCH_PRICE の注記）。
    stretch = getattr(skill, "stretch", 0.0)
    if stretch > 1.0:
        v += STRETCH_PRICE * (stretch - 1.0) * fx
    # 写し取り（§7.260）。**対象係数を掛けない** —— 効くのは自分1枚で、対象文は
    # 常に「自分」だから（掛けると「自分」の係数 0.805 が二重に効く）。
    mimic = getattr(skill, "mimic_secs", 0.0)
    if mimic > 0.0:
        v += MIMIC_PRICE * mimic
    # 上書き（§7.263）。**素の攻撃力弱体と同じ単価・同じ秒数**で、上乗せぶんを
    # 当たる割合（OVERWRITE_RATE）だけ請求する。秒数は素の節から引く——別に持たせると
    # 「素は10秒・上書きは90秒」のような読めない札が書けてしまう（engine も
    # 同じ節へ足し込むので、秒は素の節のものしかない）。
    over = getattr(skill, "overwrite", 0.0)
    if over > 0.0:
        osecs = max([s for k, a, s in skill.mods if k == "atk" and a < 0.0]
                    or [0.0])
        v += (EFFECT_PRICE["atk"] * over * 100.0 * osecs * fx) * OVERWRITE_RATE
    # 薙ぎ払い（§7.252）: 同時に N 体へ**満額で**入る ＝ 通常攻撃の総量が最大 N 倍。
    # **攻撃力バフと同じ単価で払う** —— 「1体増える」は「攻撃力 +100%」と同じ量の
    # 出力を作るからで、器を新しく較正するより既にある単価へ乗せるほうが安全。
    # ただし**上限（MOD_CAP ±50%）の外側**なので、攻撃力では買えない量が買える。
    # 対象係数は自分・味方なので `fx`（状態効果と同じ表）を通す。
    # 【注意】盤面では**満額 N 倍にはならない**（的が N 体いて、全部が射程内で、
    # どれも同じくらい良い的、のときだけ N 倍）。実測で下振れするぶんは
    # **高く請求する側**に外れるので、安全な向きである。
    cleave = getattr(skill, "cleave", 0)
    if cleave > 1:
        v += (EFFECT_PRICE["atk"] * (cleave - 1) * 100.0
              * getattr(skill, "cleave_secs", 0.0) * fx)
    drain = getattr(skill, "drain", 0.0)
    if drain > 0.0:
        v += (EFFECT_PRICE["heal"] * skill.power * drain * tc
              * target_heal_f("自分") * HEAL_TYPE_MULT.get(typ, 1.0))
    v += mods_value(skill.mods, target, fx)
    # 【§7.200】「→ その後」で遅れて始まる状態効果は、**待った秒数のぶん割り引く**。
    # 待ちは前半のいちばん長い秒数（＝engine の `_apply_skill` と同じ規則）。
    after = getattr(skill, "after_mods", ())
    if after:
        wait = max([secs for _k, _a, secs in skill.mods] or [0.0])
        v += mods_value(after, target, fx) * after_f(wait)
    # 知力比の弱体（§7.67）: 素の弱体の値段 × (知力傾き)^WITS_MOD（wk は上で算出）。
    # 相手の知力はプールの平均（≒中庸）と見なす — 智将が使えば効き、
    # 脳筋が使えば効かれにくい、という差を撃ち手側の傾きで払わせる。
    for key, amt, secs in getattr(skill, "wits_mods", ()):
        if key in ("atk", "def"):
            v += EFFECT_PRICE[key] * abs(amt) * 100.0 * secs * fx * wk
    # 代償は発動ごとに払うので他の効果と同じく段の重みに乗る。符号はマイナス。
    # 足し算の仮定は実測済み（ダメージ+代償10% の差 -3.81 対 単体 -3.56）。
    v -= sac_price(skill.sac * 100.0)
    # **上限時間の仮定を持たない。** 段の重みは対戦の集まりで測った実測値。
    v *= tier_weight(gauge_cost, gauge_init)
    v /= CARD_COST_RATE
    # 討ち取りの割増（§7.63）。表は1枚のコスト点なので、通貨変換の後に足す。
    burst = skill.power > 0.0 and skill.dur <= 0.0
    if burst:
        v += kill_premium(skill.power * tc * 100.0, target,
                          gauge_cost, gauge_init)
        # ゲージを基準より盛った一撃兵法は、発動が増えたぶん丸ごと払う（§7.64）
        v *= gauge_up_mult(gauge_cost, gauge_init, kisei)
    # 反動の戻し（§7.64）。正の価値の RECOIL_CREDIT_SHARE を超えては返さない
    # — 弱い兵法に重い反動を積んで予算だけ回収する組み方を塞ぐ。
    if getattr(skill, "self_mods", ()):
        credit = recoil_credit(skill.self_mods, gauge_cost)
        if burst:
            credit *= gauge_up_mult(gauge_cost, gauge_init, kisei)
        v -= min(credit, RECOIL_CREDIT_SHARE * max(v, 0.0))
    # 兵種の乗数（§7.147）は**最後に**掛ける — 討ち取りの割増も反動の戻しも、その札の
    # 能力値との釣り合いで測った層なので、丸ごと同じ乗数に乗る。
    return v * TYPE_EFFECT_MULT.get(typ, 1.0)


