def scut_secs_f(secs: float) -> float:
    """兵法防御の秒数係数（盤面45秒＝1.0）。錨点の折れ線・45秒以降は飽和。"""
    if secs <= 0.0:
        return 0.0
    for (x0, y0), (x1, y1) in zip(SCUT_SECS_ANCHORS, SCUT_SECS_ANCHORS[1:]):
        if secs <= x1:
            return y0 + (y1 - y0) * (secs - x0) / (x1 - x0)
    return 1.0
