# -*- coding: utf-8 -*-
"""sim/design.py -- 武将の能力値をコストから導出する設計式

**能力値を手で置かない。** 60〜80人ぶんを手で置くと、兵種ごと・コスト帯ごとの予算が
すぐ崩れる（sim/roster.py 冒頭の経緯を参照）。コストを通貨として扱いたいなら、
コストと強さの関係が式で表現されていなければならない。

================================================================================
 骨格
================================================================================
    総合値(コスト) = 枠の基礎価値 + コスト比例分            … 実カード80枚から実測
      ÷ 兵種係数（歩1.0000 / 騎1.0725 / 弓0.9685）        … この盤面で較正済み
      → 役割で 兵力 ↔ 攻撃力 へ振る（総合値は変えない）
      → 攻撃力を 武力 と 知力 へ配合（総合値は変えない）
      − 効果予算（必殺技）                                … 実カード36種で較正済み

1部隊は6枠固定なので、総合値が「基礎 + 比例分」の形なら**合計コストが同じ編成は
配分によらず総価値が等しくなる**。実測で幅2.9%まで達成できている。

================================================================================
 知力の扱い（ここが設計の要）
================================================================================
知力は「誰が賢いか」を決める**設計者の選択**であり、コストからは導出しない。
代わりに、知力を上げても**総合値が動かない**ようにする。

    攻撃力 = 武力 × (1 - w) + 知力 × w          w = INT_WEIGHT[兵種]

攻撃力はコスト曲線が決めるので、知力の傾き k（＝知力/武力）を選ぶと

    武力 = 攻撃力 / (1 - w + k·w)
    知力 = k × 武力

で一意に決まる。**攻撃力は変わらないので、智将も勇将も同じコストなら同じ強さ**に
なる。違うのは必殺技の係数（計略は知力寄り、武技は武力寄り）だけである。
諸葛亮と呂布が同じ軸で測られる問題は、これで内訳の差として表現される。

以前は知力を役割から機械的に導いていた（支援1.45倍・火力0.70倍…）が、根拠のない
placeholder だったので廃棄した。知力の傾きは**カードごとに設計者が選ぶ**。

================================================================================
 気勢（旧・必殺技ゲージ上昇率）
================================================================================
**知力とは連動させない。独立の項目にする。**

知力が威力と頻度の両方を握ると二重取りになり、知力型が一方的に強くなる。
「どれだけ強い技か（知力）」と「どれだけ早く撃てるか（気勢）」を直交させることで、
高威力・低頻度の大技型と、低威力・高頻度の手数型を別々に設計できる。

================================================================================
 効果予算（§7.5）
================================================================================
必殺技の値段をコスト点で測り、**能力値のコストから引く**。引かないと、技の強い札は
能力値まで同じだけ持つことになる。実測では技だけを差し替えた1枚の強さの幅が
**1.911 → 0.335 コスト点**（平均 +0.793 → -0.056）に縮んだ。

値段の付かない効果が2つある。移動速度とゲージ付与で、どちらも実測 0.00 である。
理由が違うので、まとめて 0 とは書けない（`effect_value` の注記）。

================================================================================
 未確定
================================================================================
- 固有特性の値段。必殺技と同じ形で測れるはずだが、誘発型は条件が揃わないと出ない
  ぶん測り方が別になる。いまは 0 のまま（特性の強い札は割安）。
- 知力の交換レート。知力1点が総合値のいくらに相当するかは測っていない。いまは
  「総合値を動かさない」形にして先送りしている。
- 移動速度・ゲージ付与の値段。発動時刻を設計の入力に入れないと線形の単価が置けない。
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Dict

from . import field as F

# 実カード80枚から実測した曲線（sim/rosterdata.py の check() が再現する）
POWER_BASE = 1.440
POWER_SLOPE = 0.2039

# 知力の傾き k = 知力 / 武力。**設計者が選ぶ軸**であり、コストや役割から導かない。
WITS_TILT = {"智将": 1.90, "才幹": 1.35, "中庸": 1.00, "武辺": 0.75, "勇将": 0.55}

# 役割は総合値を変えず、兵力 ↔ 攻撃力 の配分だけを変える（§4.6）。
# **field.ROLE_MEN の写しである。** 片方だけ触ると実カードが曲線から外れる。
ROLE_KEY = {"耐久": F.TANK, "均衡": F.BAL, "火力": F.DPS,
            "瞬発": F.BURST, "支援": F.SUP}
ROLE_MEN = {jp: F.ROLE_MEN[k] for jp, k in ROLE_KEY.items()}

# 気勢（旧ゲージ上昇率）。知力とは独立。1.0 が標準。
KISEI = {"遅": 0.85, "標準": 1.00, "速": 1.15, "俊": 1.30}


@dataclass
class Design:
    """1枚の設計指定。ここに書いたものだけが設計者の選択である。"""
    cost: float
    typ: str                    # inf / cav / arc
    role: str = "均衡"
    tilt: str = "中庸"          # 知力の傾き
    kisei: str = "標準"         # 気勢（ゲージの溜まる速さ）
    gauge_cost: float = 100.0   # 消費ゲージ（技の格）
    gauge_init: float = 0.0
    # 必殺技・固有特性に払うコスト点（`effect_value`）。**能力値から引く。**
    # ここが 0 のままだと、技の強い札が能力値も同じだけ持つことになる。
    effect: float = 0.0


def total_power(cost: float) -> float:
    """コストに対する総合値。実カードから実測した曲線。"""
    return POWER_BASE + POWER_SLOPE * cost


# 効果予算に回せるコストの上限（表示コストに対する割合）。**これを外すと壊れる。**
# 実測でコスト1の札の技は平均 0.41 点、最大 1.11 点あり、そのまま引くと能力値の
# コストが負になる。上限に当たった札は「値段どおりに払えていない」ので、
# `check()` が名指しで出す。直すのは式ではなくデータ（技を弱くするかコストを上げる）。
EFFECT_CAP = 0.45

# 超過をどこまで見逃すか（コスト点）。上限に当たった札は値段どおりに払えていないが、
# 0.5点までは設計上の許容とする（総コスト30 に対して 1.7%）。これを超えたら
# データ側で直す（技を弱くするかコストを上げる）。
EFFECT_OVER_OK = 0.5


def derive(d: Design) -> Dict[str, float]:
    """設計指定から能力値一式を導出する。"""
    # 1. コスト曲線 → 兵種係数で割る。**効果ぶんを先に引く。**
    e = min(d.effect, EFFECT_CAP * d.cost)
    p = total_power(d.cost - e) / total_power(F.BASE_COST)   # コスト5を1とする
    s = p / F.ACT_COEF[d.typ]

    # 2. 役割で 兵力 ↔ 攻撃力 を振る（積は保つので総合値は不変）
    rm = ROLE_MEN[d.role]
    men = F.CARD_MEN * s * rm
    atk = F.BASE_ATK / rm

    # 3. **武力と知力が一次値。** 攻撃力はそこからの導出。
    #
    # コスト曲線が決めるのは「攻撃力に相当する総量」なので、傾き k のもとで
    #   攻撃力 = 武力(1-w) + 知力·w = 武力(1-w+k·w)
    # を満たすように武力を決める。こうすると武力・知力を一次値として持ちながら、
    # 導出された攻撃力がコスト曲線の上に乗る。
    w = F.INT_WEIGHT[d.typ]
    k = WITS_TILT[d.tilt]
    might = atk / (1.0 - w + k * w)
    wits = k * might

    # 武力・知力は**その武将個人の力**なので、兵力の規模ぶんだけ持ち上げる。
    # 攻撃力は「その力を兵へ配ったもの」＝ 配合 ÷ (兵力/CARD_MEN) で戻る。
    # これでコストが武力にも見えるようになる（コスト2と8で武力85と141）。
    # 盤面（field.Unit）が同じ割り算をするので、攻撃力は一致する。
    f = men / F.CARD_MEN
    might *= f
    wits *= f
    atk = (might * (1.0 - w) + wits * w) / f     # 導出しなおす（保持しない）

    return {"兵力": men, "攻撃力": atk, "武力": might, "知力": wits,
            "効果予算": e, "効果超過": max(d.effect - EFFECT_CAP * d.cost, 0.0),
            "防御力": F.DEF_BY_TYPE[d.typ], "気勢": KISEI[d.kisei],
            "消費ゲージ": d.gauge_cost, "初期ゲージ": d.gauge_init,
            "総合値": men * (100.0 + F.DEF_BY_TYPE[d.typ]) / 100.0
                      * atk / F.INTERVAL[d.typ] / 1e5}


# ============================================================================
# 効果予算（§7.5）。**1枚だけがその技を持つとき**の値段を、コスト点で測った。
# ============================================================================
#
# 測り方は `sim/field.py` の物差し（総コスト1点＝残存差 0.01993）で割った値。
# 6枚全部に同じ技を持たせると Lanchester の相乗で1枚あたり14%高く出るので、
# **1枚だけ持たせて測る**（設計式が要るのはこの形である）。
#
# 単価はどれも量に対して線形だった（威力100/200/400% で 0.233/0.245/0.266）。
# 対象範囲はほぼ効かない（敵1体を1.00として 1列0.88・全体0.86・後列0.96）。
# ダメージが対象数で割られるので、広く撒くと薄まって相殺される。§7.5 の旧記述
# 「強さを決めているのは対象範囲 × 継続時間」は、割り算を入れる前の話である。
# 打ち切りダメージの値段は**威力1600%で折れる**。それより上では、1発が相手の札を
# まるごと落とせるようになり、落とした札のぶん相手の火力も消えるので複利で効く。
# 大技の段（消費300・初期140・1回）で測った値（1枚だけが持つ・コスト点）:
#
#   威力%   200    400    800   1200   1600   2100   2600   3200
#   値段  0.082  0.163  0.322  0.478  0.671  1.256  1.843  2.548
#   /100% .0408  .0406  .0403  .0399  .0420  .0598  .0709  .0796
#
# 1200%までは 0.0403 で一直線、1600%を境に傾きが約3倍になる。
# **単価1本で通すと、安い大技を6割ほど過大請求する。** 折れ線で持つ。
DAMAGE_KNEE = 16.0          # 威力1600%（power の単位で 16.0）
DAMAGE_SLOPE_HI = 0.4469    # 折れたあとの傾き（威力100% あたり）

# 継続ダメージは折れない。総威力 400〜3600% で 0.0879〜0.0881 と完全に線形だった。
# 毎秒に薄く割られるので、1ティックで札を落とすことがないためである。

# 消費ゲージの段を入れ替えたあと（§7.13）に当て直した値。
EFFECT_PRICE = {
    "damage": 0.1535,   # 打ち切り 威力100% あたり（折れる前の傾き）
    "dot":    0.3353,   # 継続の総威力100% あたり
    "heal":   0.2668,   # 回復100% あたり
    "atk":    0.00179,  # 攻撃力・命中率 1% × 1秒 × 1体 あたり
    "def":    0.00054,  # 防御力 1% × 1秒 × 1体（攻撃の1/3。防御は逓減する）
    "stun":   0.2184,   # 行動阻害 1秒 × 1体 あたり
    "spd":    0.0,      # **発動時刻しだい**。下の注記を参照
    "gauge":  0.0,      # 同上
}

# **ダメージだけが対象数で割られる。** 状態効果は対象1枚ごとに丸ごと乗るので、
# 対象数を掛ける。ここを揃え損ねると「敵1体に3秒の行動阻害」を「敵1列に3秒」と
# 同じ値段で売ることになる（先登の値段が実測の2.2倍になった）。
TARGET_N = {"全体": 6.0, "1列": 3.0, "後列": 3.0, "1体": 1.0, "自分": 1.0}

# 単価は消費ゲージ100（90秒で3回）で測った。回数が変われば比例する。
PRICE_FIRES = 3.0

# **1枚のコスト1点は、軍全体に均等配分した1点より 1.27倍 効く**（実測。-2〜+2 点で
# 1.259〜1.291 と線形）。集中させたほうが強いという Lanchester の効きである。
# 効果の値段は「軍全体の物差し」で測っているので、1枚から引くときはこれで割る。
# 割り忘れると全部の技が過大請求になる（実測で平均 -0.50 コスト点まで振れた）。
CARD_COST_RATE = 1.27


def damage_price(power: float) -> float:
    """打ち切りダメージの値段。**威力1600%で折れる**（上の注記）。"""
    if power <= DAMAGE_KNEE:
        return EFFECT_PRICE["damage"] * power
    return (EFFECT_PRICE["damage"] * DAMAGE_KNEE
            + DAMAGE_SLOPE_HI * (power - DAMAGE_KNEE))


def target_n(target: str) -> float:
    for k, v in TARGET_N.items():
        if k in target:
            return v
    return 1.0


# 90秒で入るゲージの総量。自然増加ぶん（3.20×90 = 288）に、被弾で入るぶんが
# 15ほど乗る。実測の発動回数（消費50で6回・75で4回・100で3回・150で2回）から
# 逆算して 303。**ここを連続近似のままにすると大技を過大請求する。**
# 【暫定・置き換え予定】戦闘の長さが可変になったので、この定数は「代表的な1戦」の
# 点推定にすぎない（潰走30%・上限400秒での中央値137秒から 3.20×137＋15 ＝ 453）。
#
# **点推定は筋が悪い。** 実測の分布は 71〜400秒で、1枚あたりの発動は 1.4〜7.5回まで
# 開く。しかも**戦闘の長さは編成が決める**。粘る型は自分で戦闘を長くして、そのぶん
# 技を多く撃つ。中央値で決め打つと、**長い戦闘を作る型ほど値付けから漏れる**。
# いちばん値付けしたい型がいちばん外れることになる。
#
# 段ごとの値段を、ばらつきのある対戦の集まりで直接測って持つ形へ置き換える。
# そうすれば時間の仮定が式から消え、盤面が実際に作る分布がそのまま値段に入る。
GAUGE_TOTAL = 453.0


# 段ごとの重み。**上限時間からの逆算をやめ、対戦の集まりで直接測った値**（§7.20）。
#
# 相手の性格（耐久寄り／均衡／火力寄り）・兵種・陣形を振った15通りで、同じ技
# （ダメージ 威力1000%）の値段を測った結果:
#
#   段    平均    中央値   最小    最大     標準比
#   手数  3.784  2.548  1.078  11.898  1.587
#   標準  2.385  1.286  0.510   8.506  1.000
#   大技  1.343  0.614 -0.026   6.192  0.563
#
# **同じ技が対戦相手しだいで11倍開く。** 大技は短い戦闘だとマイナスにすらなる。
# 平均と中央値が約2倍違うのは分布が右に裾を引いているためで、長い戦闘がごく一部で
# 価値を稼いでいる。値段は**平均で取る**（何戦もすれば合計は平均×戦数に寄るので、
# 通貨としてはこれが正しい）。ただし**幅は設計上の情報なので必ず併記する**。
#
# 上限時間から逆算していたときの重みは 手数2.00 / 標準1.00 / 大技0.33 で、
# 大技を6割ほど過小に、手数を2割ほど過大に見ていた。
TIER_WEIGHT = {"手数": 1.587, "標準": 1.000, "大技": 0.563}
# 値段の幅（最小/最大 ÷ 平均）。相手依存の強さ。設計時の目安。
TIER_SPREAD = {"手数": (0.28, 3.14), "標準": (0.21, 3.57), "大技": (-0.02, 4.61)}


def tier_weight(gauge_cost: float, gauge_init: float = 0.0) -> float:
    """消費ゲージと初期ゲージから段を引き当てて重みを返す。"""
    for name, (gc, gi) in GAUGE_TIER.items():
        if abs(gc - gauge_cost) < 1e-6:
            return TIER_WEIGHT[name]
    # 段の外の値は、標準を基準に消費の比で見積もる（暫定）
    return TIER_WEIGHT["標準"] * GAUGE_TIER["標準"][0] / max(gauge_cost, 1e-6)


def fires(gauge_cost: float, gauge_init: float = 0.0,
          kisei: float = 1.0, t_max: float = 90.0) -> float:
    """90秒で何回撃てるか。**切り捨てる。**

    連続近似（総量 ÷ 消費）だと消費300の技が 1.46回 と出るが、実際は1回しか
    撃てない。差の46%はまるごと過大請求になる（実測で消費200以上の技の値段が
    23%ぶん高く出ていた）。回数は整数なので、値段も整数で数える。
    """
    if gauge_cost <= 0.0:
        return 0.0
    return float(int((GAUGE_TOTAL * kisei + gauge_init) / gauge_cost))


# 消費ゲージの段（消費, 初期ゲージ）。**3つセットで意味を持つ**（§7.2）。
#
# 狙いは「弱いけど何度も出る技」と「本当の大技」を分けること。消費だけを上げると
# 1回しか撃てない技の初撃が90秒目になって間に合わないので、初期ゲージを併せて置く。
#
#   段    消費  初期   発動  初撃    1発の重み（標準を1とする）
#   手数   75    0     4回   23秒    0.5
#   標準  150   60     2回   28秒    1.0
#   大技  300  140     1回   50秒    2.0
#
# 予算（回数 × 1発の重み）はどの段でも等しい。違うのは刻みだけである。
GAUGE_TIER = {
    "手数": (75.0, 0.0),
    "標準": (150.0, 60.0),
    "大技": (300.0, 140.0),
}

# 旧 CSV の消費ゲージ（50〜175）から段への写し。
TIER_OF_COST = {50: "手数", 75: "手数", 100: "標準", 125: "標準",
                150: "大技", 175: "大技"}


def tilt_coef(skill_kind: str, typ: str, tilt: str) -> float:
    """知力の傾きが必殺技の係数を何倍にするか（中庸を1.0とする）。

    技の係数は 武力(1-v) + 知力·v、攻撃力は 武力(1-w) + 知力·w なので、傾き k に
    対して比は **(1-v+kv) / (1-w+kw)** になる。新しい定数は要らない。

        v = SKILL_WITS[技種]      武技0.00 / 範囲0.50 / 計略0.85
        w = INT_WEIGHT[兵種]      歩騎0.10 / 弓0.35

    実測（計略・歩兵・対戦15通りの平均、技の値段に対する比）:

        傾き    式      実測
        智将   1.619   1.507
        勇将   0.647   0.613

    **効くのは |v - w| の大きさである。** 攻撃力がすでに9割方は武力なので、
    武力へ寄せる余地は1割しかなく、知力側には7割5分ある。知力は効く軸、武力は
    効かない軸、という非対称は式の形から出る。
    """
    v = F.SKILL_WITS[skill_kind]
    w = F.INT_WEIGHT[typ]
    k = WITS_TILT[tilt]
    return (1.0 - v + k * v) / (1.0 - w + k * w)


def effect_value(skill, target: str = "", gauge_cost: float = 100.0,
                 gauge_init: float = 0.0, kisei: float = 1.0,
                 cost: float = F.BASE_COST, typ: str = F.INF,
                 tilt: str = "中庸") -> float:
    """必殺技1つの値段（**1枚のコスト点**）。`field.Skill` と対象文を受ける。

    実カード36種で当てた式。絶対誤差は平均 0.062・最大 0.298 コスト点。

    **移動速度とゲージ付与には値段が付かない。** どちらも実測 0.00 だった。
    理由が違うので、まとめて 0 にはできない。

    - 移動速度: 接敵が終わったあとに撃っても動いている相手がいない。初期ゲージ0
      なら 0.00、初期ゲージ100（開幕発動）なら 1.60 と、**発動時刻の崖**である。
    - ゲージ付与: 味方の消費ゲージに届かなければ1回も増えない。3秒ぶんで 0.00、
      6秒ぶんで 0.05、12秒ぶんで 0.93 と**閾値をまたぐ段**になっている。

    どちらも「量」ではなく「いつ・いくつ閾値を越えたか」で決まるので、線形の
    単価を置くと嘘になる。値段を付けたければ発動時刻を設計の入力に入れること。
    """
    n = target_n(target)
    # 【測って却下】「打撃は武力に比例するのだから、撃つ側のコストで値段も伸ばす
    # べき」と考えて補正を入れかけたが、**計器を3つ作ったら符号が揃わなかった。**
    #
    #   撃つ側のコスト        2      3      5      8     10
    #   同じコストどうしの編成  1.000  1.000  1.000  1.000  1.000
    #   総コスト30を固定      0.415  0.627  1.000  0.900  0.892
    #   武力の比（予想）      0.751  0.834  1.000  1.249  1.415
    #
    # 同コスト編成では**完全に一定**（相手の兵力も同じ割合で増えるので、残存率の差が
    # 動かない）。総コスト固定ではコスト5を頂点に両側へ落ちる。予想は単調増加。
    # §13「パラメータを振って符号が変わらないものだけを結論に使う」に従い、補正は
    # 入れない。cost 引数は残してあるが値段には効かない。
    # 打撃と回復だけが技の係数（武力・知力の配合）に乗る。状態効果は率なので乗らない。
    tc = tilt_coef(skill.kind, typ, tilt)
    v = 0.0
    if skill.dur > 0.0 and skill.power > 0.0:
        v += EFFECT_PRICE["dot"] * skill.power * skill.dur * tc
    elif skill.power > 0.0:
        v += damage_price(skill.power * tc)
    v += EFFECT_PRICE["heal"] * skill.heal * tc
    for key, amt, secs in skill.mods:
        if key == "stun":
            v += EFFECT_PRICE["stun"] * secs * n
        elif key in ("atk", "def"):
            v += EFFECT_PRICE[key] * abs(amt) * 100.0 * secs * n
    # **上限時間の仮定を持たない。** 段の重みは対戦の集まりで測った実測値。
    v *= tier_weight(gauge_cost, gauge_init)
    return v / CARD_COST_RATE


# ============================================================================
# 固有特性の値段（`sim/field.py traits` で測った表）
# ============================================================================
#
# **式を当てず、測った表をそのまま持つ。** 誘発型の値段は「いつ発動したか」で
# 決まり、発動時刻は条件ごとに違う。背水（攻撃力+25%・90秒）は必殺技と同じ式なら
# 2.96 だが実測は 0.096 で30倍ずれる。残り時間が90秒も無いうえ、発動するころには
# 本人が4割まで削れていて攻撃力を上げても乗る兵が居ないためである。19種しかない
# 固定データに、発動時刻の模型を作るほうが割に合わない。
#
# **新しい特性を足したら `python3 -m sim.field traits` で測って書き直すこと。**
TRAIT_PRICE = {
    # 常在型。陣頭が飛び抜けている
    "vanguard":  0.7097,    # 前衛の兵力 +4.5%
    "vs_wei":    0.4627,    # 該当勢力への与ダメージ +10%
    "vs_shu":    0.4627,
    "vs_go":     0.4627,
    # 誘発型
    "banner":    0.3694,
    "rearguard": 0.3137,
    "cheer":     0.2383,
    "relief":    0.2179,
    "disrupt":   0.2141,
    "diehard":   0.1633,
    "double":    0.1618,
    "legacy":    0.1443,
    "sustain":   0.1379,
    "pursuit":   0.1153,
    "laststand": 0.0959,
    "bloodpath": 0.0377,
    "chain":     0.0479,
    # ゲージ付与だった3種（呼応・号令・弔い合戦）は攻撃力の強化へ差し替えた（§7.18）。
    # ゲージ軸は値段を運べない（付与は段差、気勢は負）。
    "order":     0.1856,
    "avenge":    0.2472,
}


def trait_value(key: str) -> float:
    """固有特性1つの値段（1枚のコスト点）。必殺技と同じ通貨へ揃える。"""
    return TRAIT_PRICE.get(key, 0.0) / CARD_COST_RATE


def to_card(d: Design, name: str = "", trait: str = "",
            skill: str = "", faction: str = "") -> F.Card:
    v = derive(d)
    role_key = ROLE_KEY[d.role]
    return F.Card(cost=d.cost, stat_cost=d.cost - v["効果予算"],
                  typ=d.typ, role=role_key, name=name,
                  trait=trait, faction=faction, might=v["武力"], wits=v["知力"],
                  skill=skill, gauge_cost=d.gauge_cost,
                  gauge_rate=v["気勢"], gauge_init=d.gauge_init)


def check() -> int:
    """設計式が狙いどおりか検算する。**使う前に必ず通すこと。**"""
    bad = 0
    print("設計式の検算")

    # (1) 知力の傾きを変えても総合値が動かないか
    print("\n[1] 知力の傾きを変えても総合値が動かないか（動いたら設計が壊れている）")
    print("   {:<8}{:>10}{:>10}{:>10}{:>12}".format("傾き", "武力", "知力", "攻撃力", "総合値"))
    base = None
    for tilt in WITS_TILT:
        v = derive(Design(cost=8, typ=F.ARC, role="均衡", tilt=tilt))
        print("   {:<8}{:>10.1f}{:>10.1f}{:>10.1f}{:>12.4f}".format(
            tilt, v["武力"], v["知力"], v["攻撃力"], v["総合値"]))
        if base is None:
            base = v["総合値"]
        elif abs(v["総合値"] - base) > 1e-9:
            bad += 1
    print("   → 総合値が全行で一致すれば OK")

    # (2) 6枠・合計コスト30 で配分によらず総価値が等しいか
    print("\n[2] 6枠・合計コスト30 で配分によらず総価値が等しいか")
    for name, cs in (("均等 5×6", [5] * 6), ("偏り 7/7/4/4/4/4", [7, 7, 4, 4, 4, 4]),
                     ("極端 10/10/4/2/2/2", [10, 10, 4, 2, 2, 2])):
        tot = sum(total_power(c) for c in cs)
        print("   {:<22}{:.3f}".format(name, tot))
    vals = [sum(total_power(c) for c in cs)
            for cs in ([5] * 6, [7, 7, 4, 4, 4, 4], [10, 10, 4, 2, 2, 2])]
    spread = (max(vals) - min(vals)) / (sum(vals) / len(vals)) * 100
    print("   → 幅 {:.1f}%（0% が理想。基礎 + 比例分の形なので構造的に小さい）".format(spread))

    # (3) 役割が総合値を変えないか
    print("\n[3] 役割は内訳だけを変え、総合値を変えないか")
    print("   {:<8}{:>10}{:>10}{:>12}".format("役割", "兵力", "攻撃力", "総合値"))
    base = None
    for role in ROLE_MEN:
        v = derive(Design(cost=6, typ=F.INF, role=role))
        print("   {:<8}{:>10.0f}{:>10.1f}{:>12.4f}".format(
            role, v["兵力"], v["攻撃力"], v["総合値"]))
        if base is None:
            base = v["総合値"]
        elif abs(v["総合値"] - base) > 1e-9:
            bad += 1
    print("   → 総合値が全行で一致すれば OK")

    # (4) 効果予算を引くと能力値が下がるか（引かないと技の強い札が割安になる）
    print("\n[4] 効果予算は能力値から引かれているか")
    print("   {:<10}{:>10}{:>10}{:>10}{:>12}".format(
        "効果予算", "能力値コスト", "兵力", "武力", "総合値"))
    for e in (0.0, 0.5, 1.0, 2.0, 3.0):
        v = derive(Design(cost=5, typ=F.INF, effect=e))
        print("   {:<10.1f}{:>10.2f}{:>10.0f}{:>10.1f}{:>12.4f}".format(
            e, 5.0 - min(e, EFFECT_CAP * 5.0), v["兵力"], v["武力"], v["総合値"]))
    v0 = derive(Design(cost=5, typ=F.INF, effect=0.0))
    v1 = derive(Design(cost=5, typ=F.INF, effect=1.0))
    if not (v1["総合値"] < v0["総合値"] and v1["兵力"] < v0["兵力"]
            and v1["武力"] < v0["武力"]):
        print("   ★ 兵力・武力・総合値のどれかが下がっていない")
        bad += 1
    print("   → 兵力も武力も下がっていれば OK（片方だけなら stat_cost の配線漏れ）")

    print("\n" + ("検算 NG が {} 件".format(bad) if bad else "検算 OK"))
    return bad


if __name__ == "__main__":
    raise SystemExit(1 if check() else 0)
