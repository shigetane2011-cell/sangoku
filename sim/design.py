# -*- coding: utf-8 -*-
"""sim/design.py -- 武将の能力値をコストから導出する設計式

**能力値を手で置かない。** 60〜80人ぶんを手で置くと、兵種ごと・コスト帯ごとの予算が
すぐ崩れる（sim/roster.py 冒頭の経緯を参照）。コストを通貨として扱いたいなら、
コストと強さの関係が式で表現されていなければならない。

================================================================================
 骨格
================================================================================
    総合値(コスト) = 枠の基礎価値 + コスト比例分            … 実カード80枚から実測
      ÷ 兵種係数（歩1.0000 / 騎1.0725 / 弓0.9685）        … この盤面で較正済み
      → 役割で 兵力 ↔ 攻撃力 へ振る（総合値は変えない）
      → 攻撃力を 武力 と 知力 へ配合（総合値は変えない）
      − 効果予算（必殺技）                                … 実カード36種で較正済み

1部隊は6枠固定なので、総合値が「基礎 + 比例分」の形なら**合計コストが同じ編成は
配分によらず総価値が等しくなる**。実測で幅2.9%まで達成できている。

================================================================================
 知力の扱い（ここが設計の要）
================================================================================
知力は「誰が賢いか」を決める**設計者の選択**であり、コストからは導出しない。
代わりに、知力を上げても**総合値が動かない**ようにする。

    攻撃力 = 武力 × (1 - w) + 知力 × w          w = INT_WEIGHT[兵種]

攻撃力はコスト曲線が決めるので、知力の傾き k（＝知力/武力）を選ぶと

    武力 = 攻撃力 / (1 - w + k·w)
    知力 = k × 武力

で一意に決まる。**攻撃力は変わらないので、智将も勇将も同じコストなら同じ強さ**に
なる。違うのは必殺技の係数（計略は知力寄り、武技は武力寄り）だけである。
諸葛亮と呂布が同じ軸で測られる問題は、これで内訳の差として表現される。

以前は知力を役割から機械的に導いていた（支援1.45倍・火力0.70倍…）が、根拠のない
placeholder だったので廃棄した。知力の傾きは**カードごとに設計者が選ぶ**。

================================================================================
 気勢（旧・必殺技ゲージ上昇率）
================================================================================
**知力とは連動させない。独立の項目にする。**

知力が威力と頻度の両方を握ると二重取りになり、知力型が一方的に強くなる。
「どれだけ強い技か（知力）」と「どれだけ早く撃てるか（気勢）」を直交させることで、
高威力・低頻度の大技型と、低威力・高頻度の手数型を別々に設計できる。

================================================================================
 効果予算（§7.5）
================================================================================
必殺技の値段をコスト点で測り、**能力値のコストから引く**。引かないと、技の強い札は
能力値まで同じだけ持つことになる。実測では技だけを差し替えた1枚の強さの幅が
**1.911 → 0.335 コスト点**（平均 +0.793 → -0.056）に縮んだ。

値段の付かない効果が2つある。移動速度とゲージ付与で、どちらも実測 0.00 である。
理由が違うので、まとめて 0 とは書けない（`effect_value` の注記）。

================================================================================
 未確定
================================================================================
- 固有特性の値段。必殺技と同じ形で測れるはずだが、誘発型は条件が揃わないと出ない
  ぶん測り方が別になる。いまは 0 のまま（特性の強い札は割安）。
- 知力の交換レート。知力1点が総合値のいくらに相当するかは測っていない。いまは
  「総合値を動かさない」形にして先送りしている。
- 移動速度・ゲージ付与の値段。発動時刻を設計の入力に入れないと線形の単価が置けない。
"""

from __future__ import annotations

import math

from dataclasses import dataclass
from typing import Dict

from . import field as F

# 実カード80枚から実測した曲線（sim/rosterdata.py の check() が再現する）
POWER_BASE = 1.440
POWER_SLOPE = 0.2039

# 知力の傾き k = 知力 / 武力。**設計者が選ぶ軸**であり、コストや役割から導かない。
WITS_TILT = {"智将": 1.90, "才幹": 1.35, "中庸": 1.00, "武辺": 0.75, "勇将": 0.55}

# 役割は総合値を変えず、兵力 ↔ 攻撃力 の配分だけを変える（§4.6）。
# **field.ROLE_MEN の写しである。** 片方だけ触ると実カードが曲線から外れる。
ROLE_KEY = {"耐久": F.TANK, "均衡": F.BAL, "火力": F.DPS,
            "瞬発": F.BURST, "支援": F.SUP}
ROLE_MEN = {jp: F.ROLE_MEN[k] for jp, k in ROLE_KEY.items()}

# 役割で兵力を rm 倍したとき、攻撃力を rm^k で割る。**k=1 が「積を保つ」で、
# それは盤面では正しくない。** 盤面で測って決める（`python3 -m sim.design roles`）。
ROLE_ATK_EXP = F.ROLE_ATK_EXP

# 気勢（旧ゲージ上昇率）。知力とは独立。1.0 が標準。
KISEI = {"遅": 0.85, "標準": 1.00, "速": 1.15, "俊": 1.30}


@dataclass
class Design:
    """1枚の設計指定。ここに書いたものだけが設計者の選択である。"""
    cost: float
    typ: str                    # inf / cav / arc
    role: str = "均衡"
    tilt: str = "中庸"          # 知力の傾き
    kisei: str = "標準"         # 気勢（ゲージの溜まる速さ）
    gauge_cost: float = 100.0   # 消費ゲージ（技の格）
    gauge_init: float = 0.0
    # 必殺技・固有特性に払うコスト点（`effect_value`）。**能力値から引く。**
    # ここが 0 のままだと、技の強い札が能力値も同じだけ持つことになる。
    effect: float = 0.0
    lean: float = 0.0           # 役割寄せ（§7.56。field.role_men と同じ器）


def total_value(men: float, atk: float, typ: str) -> float:
    """1枚の総合値。**加法の通貨**（コストに線形・役割に中立）。

    集中砲火の保存量は 攻撃力×兵力²（ランチェスターの二乗則）なので、その
    平方根が「足せる量」になる。

        総合値 = 兵力 × √( 攻撃力/攻撃間隔 × (100+防御力)/100 )

    役割は 兵力 ∝ rm・攻撃力 ∝ 1/rm² なので rm が打ち消えて中立になる。
    コストは全部 兵力 に乗る（SPLIT_EXP=1）ので線形になる。

    **以前は 兵力×攻撃力 だった。** あれは「毎秒の与ダメージ」であって強さでは
    ない。兵力は殴ることと耐えることの二役をこなし、攻撃力は殴ることしかしない
    ので、積を保つ交換は兵力側が一方的に得をする（実測で役割の幅が 6.81〜27.90
    コスト点。§7.30）。
    """
    return men * math.sqrt(atk / F.INTERVAL[typ]
                           * (100.0 + F.DEF_BY_TYPE[typ]) / 100.0) / 1e3


def total_power(cost: float) -> float:
    """コストに対する総合値。実カードから実測した曲線。"""
    return POWER_BASE + POWER_SLOPE * cost


# 効果予算に回せるコストの上限（表示コストに対する割合）。**これを外すと壊れる。**
# 実測でコスト1の札の技は平均 0.41 点、最大 1.11 点あり、そのまま引くと能力値の
# コストが負になる。上限に当たった札は「値段どおりに払えていない」ので、
# `check()` が名指しで出す。直すのは式ではなくデータ（技を弱くするかコストを上げる）。
#
# **上限に当たると、そのぶん強い札になる。** 威力1500%の計略（大技）を持たせて
# 知力の傾きの残差を測ると、対戦15通りの平均で:
#
#   コスト   必要予算   上限    頭打ち   智将の残差
#     5      2.793   2.250   あり    +0.423
#     6      2.793   2.700   あり    -0.063
#     7      2.793   3.150    —     -0.075
#     8      2.793   3.600    —     +0.082
#
# **上限に当たらない範囲では残差は ±0.08 に収まる**（＝傾きの値付けは効いている）。
# 当たったときの直し方は**コストを1段上げること**。`check()` が収まるコストを
# 名指しで出す。技を弱くしても直るが、それは別の札にする話である。
EFFECT_CAP = 0.45

# 超過をどこまで見逃すか（コスト点）。上限に当たった札は値段どおりに払えていないが、
# 0.5点までは設計上の許容とする（総コスト30 に対して 1.7%）。これを超えたら
# データ側で直す（技を弱くするかコストを上げる）。
EFFECT_OVER_OK = 0.5


def derive(d: Design) -> Dict[str, float]:
    """設計指定から能力値一式を導出する。"""
    # 1. コスト曲線 → 兵種係数で割る。**効果ぶんを先に引く。**
    e = min(d.effect, EFFECT_CAP * d.cost)
    p = total_power(d.cost - e) / total_power(F.BASE_COST)   # コスト5を1とする
    s = p / F.ACT_COEF[d.typ]

    # 2. 役割で 兵力 ↔ 攻撃力 を振る（積は保つので総合値は不変）。
    # カード個別の寄せ（§7.56）も同じ交換レートを通る。**定義は field.role_men
    # の1箇所**（ROLE_MEN が field の写しなので、ここも field を呼ぶ）。
    rm = F.role_men(ROLE_KEY[d.role], d.lean)
    men = F.CARD_MEN * s * rm
    # **兵力と攻撃力の交換レートは 1:1 ではない。** 積を保つ（k=1）と、盤面では
    # 耐久が瞬発より 6.81 コスト点強くなる（総コスト30 の23%）。集中砲火の戦闘は
    # ランチェスターの二乗則に近く、戦闘力が 兵力²×攻撃力 に寄るためで、積を
    # 保つと戦闘力が兵力に比例して増えてしまう。k は盤面で測って決める（§7.30）。
    atk = F.BASE_ATK / (rm ** ROLE_ATK_EXP)

    # 3. **武力と知力が一次値。** 攻撃力はそこからの導出。
    #
    # コスト曲線が決めるのは「攻撃力に相当する総量」なので、傾き k のもとで
    #   攻撃力 = 武力(1-w) + 知力·w = 武力(1-w+k·w)
    # を満たすように武力を決める。こうすると武力・知力を一次値として持ちながら、
    # 導出された攻撃力がコスト曲線の上に乗る。
    w = F.INT_WEIGHT[d.typ]
    k = WITS_TILT[d.tilt]
    might = atk / (1.0 - w + k * w)
    wits = k * might

    # 武力・知力は**その武将個人の力**なので、兵力の規模ぶんだけ持ち上げる。
    # 攻撃力は「その力を兵へ配ったもの」＝ 配合 ÷ (兵力/CARD_MEN) で戻る。
    # これでコストが武力にも見えるようになる（コスト2と8で武力85と141）。
    # 盤面（field.Unit）が同じ割り算をするので、攻撃力は一致する。
    f = men / F.CARD_MEN
    might *= f
    wits *= f
    atk = (might * (1.0 - w) + wits * w) / f     # 導出しなおす（保持しない）

    return {"兵力": men, "攻撃力": atk, "武力": might, "知力": wits,
            "効果予算": e, "効果超過": max(d.effect - EFFECT_CAP * d.cost, 0.0),
            "防御力": F.DEF_BY_TYPE[d.typ], "気勢": KISEI[d.kisei],
            "消費ゲージ": d.gauge_cost, "初期ゲージ": d.gauge_init,
            "総合値": total_value(men, atk, d.typ)}


# ============================================================================
# 効果予算（§7.5）。**1枚だけがその技を持つとき**の値段を、コスト点で測った。
# ============================================================================
#
# 測り方は `sim/field.py` の物差し（総コスト1点＝残存差 0.01993）で割った値。
# 6枚全部に同じ技を持たせると Lanchester の相乗で1枚あたり14%高く出るので、
# **1枚だけ持たせて測る**（設計式が要るのはこの形である）。
#
# 単価はどれも量に対して線形だった（威力100/200/400% で 0.233/0.245/0.266）。
# 対象範囲はほぼ効かない（敵1体を1.00として 1列0.88・全体0.86・後列0.96）。
# ダメージが対象数で割られるので、広く撒くと薄まって相殺される。§7.5 の旧記述
# 「強さを決めているのは対象範囲 × 継続時間」は、割り算を入れる前の話である。
# 【訂正】以前ここに「打ち切りダメージは威力1600%で折れる」と書いていたが、
# **あれは単一の対戦で測ったせいだった。** その噛み合わせでは1発が相手の札を落として
# 複利が効いていたが、15通りの平均では均されて消える。
#
#   威力%     600    1500    2500
#   実測    0.696   1.800   2.807
#   100%あたり  —   0.123   0.101
#
# ほぼ原点を通る直線。崖ではなく、特定の噛み合わせの話だった。折れ線は撤去する。
# §13「帯に入る値を見つけたら、その隣を測って崖の上でないか確かめる」を、
# **対戦相手の側でもやる**必要があった。

# 単価。**すべて15通りの対戦の平均で当てた値**（§7.22）。段の重みと同じ基準。
# 以前は単価を単一の対戦、段の重みを15通りの平均で測っていて基準が違い、
# 絶対水準が最大2.3倍ずれていた（威力1500%の計略が式2.73／実測1.80）。
DAMAGE_K = 0.1518     # 威力100%（power=1.0）のときの値段
DAMAGE_EXP = 0.9512    # 威力に対する冪。1.0 だと低威力を2割高く見積もる

EFFECT_PRICE = {
    "damage": 0.3537,   # 打ち切り 威力100% あたり
    "dot": 0.382287,   # 継続の総威力100% あたり
    "heal": 0.494315,   # 回復100% あたり
    "atk": 0.000724623, # 攻撃力・命中率 1% × 1秒 × 1体 あたり
    "def": 0.000305964, # 防御力 1% × 1秒 × 1体
    "stun": 0.119597,   # 行動阻害 1秒 × 1体 あたり
    # scut（必殺技防御）は対象係数表が使えない（下の TARGET_SCUT_PRICE）
    "chaos": 0.000897109, # 混乱。**攻撃力の下げ幅に直した1% × 1秒 × 1体**あたり
    "spd":    0.0,      # **発動時刻しだい**。下の注記を参照
    "gauge":  0.0,      # 廃止（§7.18）
}


def chaos_equiv(c: float) -> float:
    """混乱の量を**攻撃力の下げ幅**に直す。値段はこの換算のうえで線形になる。

    混乱を受けた側は出力が 1/(1+c) 倍に落ち、そのうち CHAOS_FF·c/(1+c) が
    味方へ向く。こちらから見れば「減ったぶん」と「相手の味方に入るぶん」の
    両方が得なので、その和を等価な下げ幅とする。

    **量に対して飽和する形をそのまま持つ。** 混乱 20/40/80% の実測比は
    0.633 / 1.000 / 1.367 で、この式の比 0.624 / 1.000 / 1.412 と合う。
    量に線形の単価を置くと 80% を 2 倍に見積もって値付けが崩れる。

    15通りの集まりで測った単価は 量 10〜40%・秒数 10〜40・対象 1〜6 の
    27 通りで 0.00079〜0.00114 に収まった（換算前は 9 倍に開く）。
    残る傾きは秒数で、40秒だと 0.0008 まで下がる。長い状態異常が飽和するのは
    攻撃力低下と同じ性質で、そちらの単価 0.000773 も30秒で当てた値である。
    """
    m = 1.0 / (1.0 + c)
    ff = F.CHAOS_FF * c / (1.0 + c)
    return (1.0 - m) + 2.0 * m * ff


def damage_price(power: float) -> float:
    """打ち切りダメージの値段。**威力に線形ではない（冪 1.119）。**

        値段 = 0.0931 × (威力/100)^1.119

    **大きい技ほど威力100%あたりの価値が高い。** 15通りのパネルで測った
    100%あたりの値段は 0.106（威力200%）→ 0.138（威力2500%）と単調に上がる。
    直線で当てると低威力を2割高く・高威力を6%安く見積もる（比 0.81〜1.06）。
    冪にすると最大ずれ 5.3%。

    | 威力% | 200 | 300 | 400 | 600 | 900 | 1500 | 2500 |
    | 比   |1.049|1.009|0.971|0.957|0.952|1.053 |1.014 |

    【訂正の経緯】以前ここに「威力1600%で3倍に折れる」という折れ線を置き、
    **単一の対戦のせいだった**と判明して撤去した（§7.5）。今回は 15通りの
    パネルで、しかも 200〜2500% を7点測って**なめらかな曲がり**であることを
    確かめている。崖ではない。折れ線と冪は別物である。

    曲がる理由は、1発で相手の札を落とすと**その札の残りの出力を丸ごと奪える**
    ことにあると見ている（削るだけでは奪えない）。集中砲火の盤面では
    強さが 兵力²×攻撃力 に乗るので、まとめて減らすほうが効く（§7.30）。
    """
    return DAMAGE_K * (power ** DAMAGE_EXP)


