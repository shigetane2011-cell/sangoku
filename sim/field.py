def cmd_calibrate(args) -> None:
    """兵種相性の表を対戦ごとに較正する。

    1つの値では揃わない。コスト点→勝敗の感度が対戦ごとに違うため、同じ 1.0 を
    与えても 歩/騎 は +1.918、騎/弓 は +0.762 にしかならない。対戦ごとに感度を
    測って解くと1回の反復で揃う。
    """
    global TYPE_EDGE_COST
    pairs = [(INF, CAV, 0, 1, "歩→騎"), (CAV, ARC, 1, 2, "騎→弓"),
             (ARC, INF, 2, 0, "弓→歩")]
    target = args.target
    print(f"兵種相性の表の較正（目標 各方向 +{target:.2f} コスト点）")
    print()
    for it in range(4):
        M, r, _ = type_table(args.dt, args.rot)
        cur = [M[(i, j)] for _, _, i, j, _ in pairs]
        print("  反復{}  ".format(it)
              + "  ".join("{} {:+.3f}".format(n, v)
                          for (_, _, _, _, n), v in zip(pairs, cur))
              + "   推移幅 {:.3f}".format(max(r) - min(r)))
        if max(abs(v - target) for v in cur) < 0.05:
            break
        for (ti, tj, i, j, _), v in zip(pairs, cur):
            k = TYPE_EDGE_COST[(ti, tj)]
            TYPE_EDGE_COST[(ti, tj)] = k + 0.5
            M2, _, _ = type_table(args.dt, args.rot)
            slope = (M2[(i, j)] - v) / 0.5
            TYPE_EDGE_COST[(ti, tj)] = (k + (target - v) / slope
                                        if abs(slope) > 1e-6 else k)
    print()
    print("  較正結果:")
    for ti, tj, _, _, n in pairs:
        print("    {} : {:.4f}".format(n, TYPE_EDGE_COST[(ti, tj)]))


