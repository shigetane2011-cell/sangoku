def margin(a: Army, b: Army, dt: float = 0.5) -> float:
    """a と b の残存兵力率の差。勝敗ではなく**差そのもの**を返す。"""
    r = simulate(a, b, dt=dt)
    return r["ra"] - r["rb"]


def cost_yardstick(dt: float = 0.5) -> float:
    """「総コストを 1 増やすと残存兵力率の差がいくつ動くか」を測る物差し。

    加算性を勝率で測ると、差が数値の埃ほどしかなくても勝敗は 0/100 に振れる。
    実際に測ると、9/1 まで偏らせたときの差は 4e-3 しかないのに、勝率は ±16.7〜50%
    と出る。**勝率は埃の符号を 増幅 しているだけで、強さを測っていない。**
    そこで、配分による差を「総コスト何点ぶんか」に換算して報告する。
    """
    base = flat_army()
    pts = []
    for extra in (0.3, 0.6, 1.2, 3.0, 6.0):
        v = flat_army(cost=BASE_COST + extra / 6.0)
        pts.append((extra, margin(v, base, dt)))
    # 原点を通る直線で当てる（差 = slope × 追加コスト）
    num = sum(x * y for x, y in pts)
    den = sum(x * x for x, _ in pts)
    return num / den


def cmd_cost(args) -> None:
    print("コストの加算性（総コスト30を固定し、配分だけ動かす）")
    print()
    print("【1】まず物差しを作る: 総コストを増やすと残存兵力率の差はどう動くか")
    print("  {:<14}{:>12}{:>16}".format("追加コスト", "差", "差/コスト"))
    base = flat_army()
    for extra in (0.3, 0.6, 1.2, 3.0, 6.0):
        m = margin(flat_army(cost=BASE_COST + extra / 6.0), base, args.dt)
        print("  +{:<13.1f}{:>12.2e}{:>16.4f}".format(extra, m, m / extra))
    slope = cost_yardstick(args.dt)
    print(f"  → 総コスト1点 = 差 {slope:.4f}")
    print()

    print("【2】配分を偏らせたときの差を、コスト何点ぶんかへ換算する")
    print("  完全に加法的なら 0.00 点。30点中の何%かで見る。")
    print("  {:<8}{:>12}{:>14}{:>12}{:>12}".format(
        "配分", "差(中央値)", "コスト換算", "30点中", "勝率(参考)"))
    for d, name in ((1.0, "6/4"), (2.0, "7/3"), (3.0, "8/2"), (4.0, "9/1")):
        ms = []
        for i in range(6):
            for j in range(6):
                if i != j:
                    ms.append(abs(margin(split_army(d, i, j), base, args.dt)))
        ms.sort()
        med = ms[len(ms) // 2]
        eq = med / slope
        print("  {:<8}{:>12.2e}{:>14.3f}{:>11.2f}%{:>12.1f}".format(
            name, med, eq, 100.0 * eq / 30.0, cost_panel(d, args.dt) + 50.0))
    print()
    print("  勝率の列は飽和して見えるが、実体は上の「30点中」の列である。")
    print("  9/1 まで偏らせても総コスト 0.3点未満ぶんしか動いていない。")
    print()

    print("【3】時間刻みを振って符号が変わらないか（結論に使える条件）")
    print("  {:<8}".format("配分") + "".join(f"dt={d:<10}" for d in DTS))
    for d, name in ((2.0, "7/3"), (4.0, "9/1")):
        row = f"  {name:<8}"
        for dt in DTS:
            sl = cost_yardstick(dt)
            ms = [margin(split_army(d, i, j), base, dt)
                  for i in range(6) for j in range(6) if i != j]
            ms.sort()
            row += "{:>+9.4f}   ".format(ms[len(ms) // 2] / sl)
        print(row)
    print("  （コスト点ぶんの中央値。符号と大きさが dt で変わらないことを見る）")


def yardstick(dt: float = 0.5) -> float:
    """総コスト1点あたり、残存兵力率の差がいくつ動くか。"""
    base = flat_army()
    pts = [(e, margin(flat_army(cost=BASE_COST + e / 6.0), base, dt))
           for e in (0.3, 0.6, 1.2, 3.0, 6.0)]
    return sum(x * y for x, y in pts) / sum(x * x for x, _ in pts)


def matchup_cost(a: Army, b: Army, slope: float, dt: float = 0.5,
                 rot: int = 6) -> float:
    """編成 a の b に対する優位を**コスト点**で返す。

    枠の並びを回して多数の局面を作り、左右を入れ替えて反対称化する。左右の偏りは
    定義上打ち消えるので、残るのは中身の差だけになる。勝率は使わない
    （総コスト +0.1点で 100% に飽和するため。`cmd_triangle` の較正を参照）。
    """
    tot = 0.0
    n = 0
    for r in range(rot):
        ar = Army(a.cards[r:] + a.cards[:r], a.form)
        for t in range(rot):
            br = Army(b.cards[t:] + b.cards[:t], b.form)
            tot += (margin(ar, br, dt) - margin(br, ar, dt)) / 2.0
            n += 1
    return (tot / n) / slope


def decompose(items, make, dt: float = 0.5, rot: int = 6):
    """総当たり表を作り、推移成分と巡回成分へ分ける。

    推移成分 r_i は「単にどれかが強い」分で、**値付けで消せる**。
    巡回成分 c は「本物の三すくみ」で、値付けでは動かない。
    分けずに見ていると、どちらが原因か区別できない。
    """
    slope = yardstick(dt)
    k = len(items)
    M = {}
    for i in range(k):
        M[(i, i)] = 0.0
        for j in range(i + 1, k):
            m = matchup_cost(make(items[i]), make(items[j]), slope, dt, rot)
            M[(i, j)] = m
            M[(j, i)] = -m
    rating = [sum(M[(i, j)] for j in range(k)) / k for i in range(k)]
    cyc = None
    if k == 3:
        cyc = (M[(0, 1)] + M[(1, 2)] + M[(2, 0)]) / 3.0
    return M, rating, cyc


def type_table(dt: float = 0.5, rot: int = 6):
    """3兵種の総当たり表と、その推移成分・巡回成分。"""
    return decompose((INF, CAV, ARC), type_army, dt, rot)


FORMS = (("標準(前衛3)", FORM_STANDARD), ("広く浅い(前衛4)", FORM_WIDE),
         ("狭く深い(前衛2)", FORM_DEEP))
FORM_TYPS = (INF, INF, CAV, ARC, ARC, CAV)


def form_table(forms=FORMS, dt: float = 0.5, rot: int = 6):
    """陣形の総当たり表。中身（6枚）は同じで陣形だけ変える。"""
    return decompose([f for _, f in forms],
                     lambda f: mixed_role_army(FORM_TYPS, f), dt, rot)


def cmd_price(args) -> None:
    """行動面の係数をこの盤面で測り直す（3兵種の総当たりで）。

    §6.1 の値（歩1.00 / 騎0.90 / 弓1.12）は旧レーンエンジンのもの。歩兵基準の
    1本だけで合わせると、残り1組のずれが取れずに三すくみが歪む。総当たり表の
    **推移成分**を係数へ戻すと、3方向が同時に揃う。
    """
    global ACT_COEF, TYPE_BONUS
    keep_b = TYPE_BONUS
    TYPE_BONUS = 0.0
    ACT_COEF = {INF: 1.0, CAV: 1.0, ARC: 1.0}
    T = (INF, CAV, ARC)
    print("行動面の係数の測り直し（兵種補正 0、3兵種の総当たり）")
    print("  推移成分がすべて 0 になるまで係数へ戻す。単位はコスト点（総コスト30）。")
    print()
    print("  {:<6}{:>9}{:>9}{:>9}{:>11}{:>9}{:>9}{:>9}".format(
        "反復", "歩", "騎", "弓", "巡回c", "係数歩", "係数騎", "係数弓"))
    for it in range(5):
        _, r, cyc = type_table(args.dt, args.rot)
        print("  {:<6}{:>+9.3f}{:>+9.3f}{:>+9.3f}{:>+11.4f}"
              "{:>9.4f}{:>9.4f}{:>9.4f}".format(
                  it, r[0], r[1], r[2], cyc,
                  ACT_COEF[INF], ACT_COEF[CAV], ACT_COEF[ARC]))
        if max(abs(x) for x in r) < 0.02:
            break
        # 補正の刻み幅はコスト曲線に依存する。
        #
        # 正規化した強さは p(c) = F + (1-F)·c/5（F = POWER_BASE_FRAC）なので、
        # **1コスト点の重みは (1-F)/5** である。r/30 と決め打ちすると、F を
        # 変えたときに刻みが (1-F) 倍ずれる。実際 F=0.585 で 4.3倍の過剰補正に
        # なり、係数が負へ飛んで発散した（騎兵 -0.687、三すくみ ±57コスト点）。
        step = (1.0 - POWER_BASE_FRAC) / 30.0
        new = {T[i]: ACT_COEF[T[i]] * (1.0 + r[i] * step) for i in range(3)}
        k = new[INF]
        # 係数は正でなければ意味を持たない。発散を早期に止める。
        ACT_COEF = {t: min(max(new[t] / k, 0.2), 5.0) for t in T}
    print()
    print("  採用: 歩 {:.4f} / 騎 {:.4f} / 弓 {:.4f}".format(
        ACT_COEF[INF], ACT_COEF[CAV], ACT_COEF[ARC]))
    print("  残った巡回成分 c = {:+.4f} コスト点（素の三すくみの向きと大きさ）".format(cyc))
    TYPE_BONUS = keep_b


