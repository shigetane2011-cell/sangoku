def cyc_sign(i: str, j: str) -> float:
    """兵種 i から見た j との相性を、較正済みの係数付きで返す。

    +なら i が有利、-なら不利、0 なら同兵種。値は TYPE_EDGE_COST の表から引く。
    """
    if BEATS.get(i) == j:
        return TYPE_EDGE_COST[(i, j)]
    if BEATS.get(j) == i:
        return -TYPE_EDGE_COST[(j, i)]
    return 0.0


def type_edge(a: "Army", b: "Army") -> float:
    """編成 a の b に対する兵種相性。-1〜+1 の連続量。

    **攻撃ごとに掛けると純粋な巡回項にならない。** 割合で効くので、射程で長く
    撃てる弓兵ほど同じ % でも得をし、推移成分（単にどれかが強い）が混ざる。
    実測では兵種補正を上げるほど推移幅が 0.005 → 0.586 と育った。
    そこで陣形と同じく**編成どうしの相性**として1つの数にまとめる。
    兵種のコスト比で重みを付けるので混成でも連続に決まり、分岐を含まない。
    返り値の単位は**コスト点**（表の係数込み）。反対称（edge(a,b) = -edge(b,a)）。
    """
    ta = _type_share(a)
    tb = _type_share(b)
    return sum(wa * tb[j] * cyc_sign(i, j)
               for i, wa in ta.items() for j in tb)


def _type_share(army: "Army") -> Dict[str, float]:
    tot = sum(c.cost for c in army.cards) or 1.0
    out = {t: 0.0 for t in TYPES}
    for c in army.cards:
        out[c.typ] += c.cost / tot
    return out

