def _weights(u: Unit, foes: List[Unit], gaps: List[float]) -> List[float]:
    """射撃の重み。射程は縁からの距離で測り、射線が通るぶんだけ当たる。"""
    out = []
    for f, d in zip(foes, gaps):
        rat = f.ratio()
        # ratio を掛けて全滅した札を撃ち続けないようにし、exp(FOCUS(1-ratio)) で
        # 弱った札へ寄せる。どちらも ratio の連続関数で、分岐を含まない。
        out.append(smooth_gate(d, u.rng, RANGE_SOFT) * rat
                   * math.exp(FOCUS * (1.0 - rat)) * _sight(u, f, foes))
    return out


def _fire_traits(ua, ub, t, retired, ev, seen, fired_skill=None) -> None:
    """誘発型の固有特性を発火させる（§6.6）。中身は必殺技と同じ器で処理する。

    閾値をまたぐ判定なので**分岐**であり、時間刻みに弱い。移動の規則と違って
    連続化できない（「撤退した」は本質的に離散）ので、dt を振って結論の符号が
    変わらないかを別途確かめること。

    fired_skill には、このティックで必殺技を撃った札の集合を渡す（ally_skill 用）。
    """
    fired_skill = fired_skill or set()
    for own, foe in ((ua, ub), (ub, ua)):
        newly_own = [x for x in own if x in retired["new"]]
        newly_foe = [x for x in foe if x in retired["new"]]
        for u in own:
            spec = TRAITS.get(u.trait)
            if spec is None or u.men <= 0.0:
                continue
            cond, target, cap, sk, jp = spec
            if u.fired >= cap:
                continue
            hit = ((cond == "ally_retreat" and any(x is not u for x in newly_own))
                   or (cond == "enemy_retreat" and bool(newly_foe))
                   or (cond == "self_low_hp" and u.ratio() < LOW_HP)
                   or (cond == "ally_skill"
                       and any(x in fired_skill for x in own if x is not u)))
            if not hit:
                continue
            u.fired += 1
            # 同じ特性は1戦に1回だけ実況へ出す（何度も発動するので）
            show = ev is not None and ("誘", u.trait, u.side) not in seen
            if show:
                seen.add(("誘", u.trait, u.side))
            _apply_skill(u, sk, target, own, foe, t, src=u.trait,
                         ev=ev if show else None, seen=seen, name=jp,
                         kind_jp="誘発")


def x_rate(u: Unit) -> float:
    """ゲージの溜まる速さ。気勢の状態効果（率）を掛ける。"""
    return u.gauge_rate * u.rate_mult


@dataclass(frozen=True)
class Skill:
    """必殺技1つぶんの中身。CSV の効果文から作る（`_parse_skill`）。

    **盤面が持っていない量へは写さない。** 命中率はダメージ式に無いので、
    命中率 -7% は攻撃力 -7% と同じ意味になる（期待ダメージが同じ倍率で落ちる）。
    別の器を作ると「命中率だけ下げる技」が実は何もしない、という嘘になる。
    """
    power: float = 0.0      # ダメージ威力。dur > 0 なら**毎秒**の量
    kind: str = "melee"     # 知力の効き方（SKILL_WITS）
    dur: float = 0.0        # 継続秒数。0 は打ち切り
    heal: float = 0.0       # 回復量（ダメージと同じ係数に掛ける）
    mods: Tuple[Tuple[str, float, float], ...] = ()   # (種別, 量, 秒数)


def _skill_kind(effect: str, target: str) -> str:
    if "継続ダメージ" in effect or "ダメージ" not in effect:
        return "scheme"
    return "melee" if "1体" in target else "area"


def _skill_power(effect: str) -> Tuple[float, float]:
    """効果文から「威力X%」と持続秒数を取り出す。

    戻り値は (威力, 秒数)。秒数 0 は打ち切り（1発で入る）。秒数 > 0 のときの威力は
    **毎秒の量**である。総量は 威力 × 秒数 なので、以前の「秒数を掛けて1発にする」
    実装と総量は同じだが、入り方が違う。
    """
    m = re.search(r"威力(\d+)%", effect)
    if not m:
        return 0.0, 0.0
    p = float(m.group(1)) / 100.0
    if "継続ダメージ" in effect:
        d = re.search(r"（(\d+)秒）", effect)
        return p, float(d.group(1)) if d else 10.0
    return p, 0.0


def _skill_heal(effect: str) -> Tuple[float, float]:
    """効果文から回復量と持続秒数を取り出す。戻り値は (量, 秒数)。

    CSV は「回復 攻撃力の260%」の形。攻撃力ではなく**武力・知力から引く**
    （ダメージと同じ係数）。攻撃力から引くと兵力の多い札ほど回復が薄くなり、
    耐久役の回復技だけが弱くなる。
    """
    m = re.search(r"回復\s*攻撃力の(\d+)%", effect)
    if not m:
        return 0.0, 0.0
    p = float(m.group(1)) / 100.0
    d = re.search(r"継続回復.*?（(\d+)秒）", effect)
    return (p, float(d.group(1))) if d else (p, 0.0)


# 効果文の見出し → 盤面の器。命中率は攻撃力へ写す（上の Skill の注記）。
_MOD_KEY = {"攻撃力": "atk", "命中率": "atk", "防御力": "def", "移動速度": "spd",
            "気勢": "rate"}


def _skill_mods(effect: str) -> Tuple[Tuple[str, float, float], ...]:
    """効果文から「攻撃力 +9%（15秒）」などの状態効果を取り出す。

    符号が向き先を決める。**プラスは自分（または味方）、マイナスは対象**。
    「突撃 / 敵1体（最前） / ダメージ 威力160% + 移動速度 +30%（12秒）」の
    +30% は敵の速度を上げる技ではなく、突っ込む自分の速度である。
    """
    out = []
    for m in re.finditer(
            r"(攻撃力|命中率|防御力|移動速度|気勢)\s*([+-]\d+)%（(\d+)秒）", effect):
        out.append((_MOD_KEY[m.group(1)], float(m.group(2)) / 100.0,
                    float(m.group(3))))
    m = re.search(r"混乱\s*(\d+(?:\.\d+)?)%（(\d+)秒）", effect)
    if m:
        out.append(("chaos", float(m.group(1)) / 100.0, float(m.group(2))))
    m = re.search(r"行動阻害\s*(\d+)秒", effect)
    if m:
        # 行動阻害は「攻撃も移動も止まる」。専用の器を作らず、両方を -100% にする。
        out.append(("stun", -1.0, float(m.group(1))))
    # 【廃止】ゲージ付与。**段差なので値段が付かない。**
    # 「自然増加のN秒ぶん」でも「消費のX%」でも、受け手が1回ぶんの閾値を越えるか
    # 越えないかで 0 か丸ごと1回ぶんになる。実測（味方全体・標準の段・2回）で
    # 消費の 2/8/16% は味方の発動回数を1回も増やさず（値段ほぼ0）、40% で突然
    # 2倍になった（+2.4コスト点）。§13「帯に入る値を見つけたら、その隣を測って
    # 崖の上でないか確かめる」に照らして、崖の上には置かない。
    # 代わりに **気勢（ゲージの溜まる速さ）を率で上げる**。連続量なので他の状態効果と
    # 同じ形で値段が付く（§4.6「補正はすべて率で定義する」）。
    # 旧表記は読み込みだけ残す。
    # 旧表記「自然増加のN秒ぶん」は §4.6 の「固定値で与えるとゲージ上昇率の低い
    # 武将ほど得をする」を避けるためだったが、**消費ゲージの段を作ったことで別の
    # 問題が出た**。3〜6秒ぶん（10〜19）は消費150〜300 に対して数%にしかならず、
    # 1回も発動を増やせない。実測で5種とも値段 0.00。割合なら段が変わっても意味が
    # 保たれる（「味方全体のゲージを4割進める」）。
    m = re.search(r"ゲージ付与\s*消費の(\d+)%", effect)
    if m:
        out.append(("gauge", float(m.group(1)) / 100.0, 0.0))
    else:
        m = re.search(r"ゲージ付与\s*自然増加の(\d+)秒ぶん", effect)
        if m:      # 旧表記。自然増加ぶんを消費100に対する割合へ写す
            out.append(("gauge", float(m.group(1)) * GAUGE_PER_SEC / 100.0, 0.0))
    return tuple(out)


def _parse_skill(effect: str, target: str) -> Skill:
    p, dur = _skill_power(effect)
    heal, hdur = _skill_heal(effect)
    return Skill(power=p, kind=_skill_kind(effect, target), dur=dur or hdur,
                 heal=heal, mods=_skill_mods(effect))


def _skill_targets(target: str, u, foe, own):
    """技の対象を返す。味方対象なら own の側から選ぶ。

    レーンが無いので「1列」は**盤面上で近い3枚**へ写す（旧実装は兵力の多い順に
    3枚だった。位置と無関係なので、前衛を守る技が後衛に飛ぶことがあった）。
    """
    if "味方" in target or "自分" in target:
        pool = [x for x in own if x.men > 0.0]
        if not pool:
            return []
        if "自分" in target:
            return [u] if u.men > 0.0 else []
        if "全体" in target:
            return pool
        if "残兵力が最少" in target:
            return [min(pool, key=lambda x: x.ratio())]
        if "1列" in target:
            return sorted(pool, key=lambda x: _d2(u, x))[:3]
        return [min(pool, key=lambda x: x.ratio())]
    if "全体" in target:
        return list(foe)
    if "後列" in target:
        r = [x for x in foe if not x.is_front]
        return r or list(foe)
    if "残兵力が最少" in target:
        alive = [x for x in foe if x.men > 0]
        return [min(alive, key=lambda x: x.ratio())] if alive else []
    if "1列" in target:                  # レーンは無いので「最も近い3枚」へ写す
        alive = [x for x in foe if x.men > 0]
        return sorted(alive, key=lambda x: _d2(u, x))[:3]
    alive = [x for x in foe if x.men > 0]
    return [max(alive, key=lambda x: x.men)] if alive else []


def _d2(a, b) -> float:
    return (a.x - b.x) ** 2 + (a.y - b.y) ** 2


def _vs_faction(u: Unit, f: Unit) -> bool:
    """対勢力の常在型が当たるか。**群雄にはどの対勢力も当たる**（CSV の備考）。"""
    want = FACTION_OF.get(u.trait)
    return want is not None and f.faction in (want, "群雄")


def _skill_line(u: Unit, name: str, tstr: str, tgts, kind: str,
                amount: float, secs: float = 0.0) -> str:
    """必殺技・固有特性の実況行。**数値ではなく出来事として書く**（§9.3）。"""
    who = _who(u)
    n = len(tgts)
    side = "敵" if not ("味方" in tstr or "自分" in tstr) else "味方"
    if n == 1 and tgts[0] is u:
        where = "自身"
    elif n == 1:
        where = _who(tgts[0])
    else:
        where = "{}{}隊".format(side, n)
    if kind == "dot":
        return "{}、{}。{}が燃え続ける（毎分{:,.0f}人・{:.0f}分）。".format(
            who, name, where, per_min(amount), mins(secs))
    if kind == "damage":
        return "{}、{}。{}に{:,.0f}人の損害。".format(who, name, where, amount)
    if kind == "heal":
        return "{}、{}。{}が{:,.0f}人を立て直す。".format(who, name, where, amount)
    if kind == "stun":
        return "{}、{}。{}の足が{:.0f}分止まる。".format(
            who, name, where, mins(secs))
    if kind == "chaos":
        return "{}、{}。{}の隊列が乱れ、同士討ちが始まる（{:.0f}分）。".format(
            who, name, where, mins(secs))
    if kind == "buff":
        return "{}、{}。{}の勢いが上がる（{:+.0%}・{:.0f}分）。".format(
            who, name, where, amount, mins(secs))
    return "{}、{}。{}の動きが鈍る（{:+.0%}・{:.0f}分）。".format(
        who, name, where, amount, mins(secs))


# 技のフェーズ中だけ有効な兵力の蓄積器。**None なら即時に反映する。**
#
# 通常ダメージは da/db に貯めてティックの最後にまとめて引く（§5.1 の同時解決）が、
# 必殺技と固有特性はその場で men を書き換えていた。`_fire_skills(ua, ub)` を撃ち
# きってから `_fire_skills(ub, ua)` を撃つので、**先に撃った側が相手の撃ち手を倒すと
# 相手は撃てない**。同じ登録どうしのマッチで A が3回・B が2回撃ち、零点が
# 0.0166 になっていた（1部隊戦の合成カードでは技が当たらず表に出なかった）。
_SKILL_DELTA = None


def _men_add(f: Unit, d: float) -> None:
    """兵力を増減する。技のフェーズ中なら蓄積器へ回す。"""
    if _SKILL_DELTA is None:
        f.men = max(min(f.men + d, f.men0), 0.0)
    else:
        _SKILL_DELTA[id(f)] = (f, _SKILL_DELTA.get(id(f), (f, 0.0))[1] + d)


def _open_men_window() -> None:
    """技のフェーズを開く。**関数越しにするのは、simulate の中で代入すると
    ローカル変数になって黙って効かなくなるため。**"""
    global _SKILL_DELTA
    _SKILL_DELTA = {}


def _flush_men() -> None:
    """溜めた増減をまとめて反映する。**両側が撃ち終わってから呼ぶ。**"""
    global _SKILL_DELTA
    if _SKILL_DELTA is None:
        return
    for f, d in _SKILL_DELTA.values():
        f.men = max(min(f.men + d, f.men0), 0.0)
    _SKILL_DELTA = None


def _apply_skill(u: Unit, sk: "Skill", tstr: str, own, foe, t: float,
                 src: str = "", ev=None, seen=None, name: str = "",
                 kind_jp: str = "必殺技") -> None:
    """必殺技1発ぶんの効果を盤面へ入れる。**固有特性も同じ器を通る。**

    src は §6.5 の同名判定に使う出どころ（技名または特性キー）。
    """
    tgts = _skill_targets(tstr, u, foe, own)
    if not tgts:
        return
    v = SKILL_WITS[sk.kind]
    coef = u.might * (1.0 - v) + u.wits * v
    n = max(len(tgts), 1)
    name = name or src

    def say(kind, amount, secs=0.0, mag=0.0, jp=None):
        """実況行を1本積む。**効いた量をそのまま持たせる**（行の取捨に使う）。"""
        if ev is None or not name:
            return
        # **効かなかったものは語らない。** 「自身が92人を立て直す」のような行が出ると、
        # 起きた出来事としては正しくても実況としては嘘に近い（読者は意味のある量だと
        # 受け取る）。対象の兵力に対する割合で足切りする。
        if kind in ("damage", "heal", "dot"):
            base = sum(f.men0 for f in tgts) or 1.0
            total = amount * (secs if kind == "dot" else 1.0)
            if total / base < NARRATE_FLOOR:
                return
        k = jp or kind_jp
        ev.append(Event(t, k, LINE_PRIO[k],
                        _skill_line(u, name, tstr, tgts, kind, amount, secs),
                        mag))

    # 状態効果。**符号が向き先を決める**（_skill_mods の注記）。
    ally = "味方" in tstr or "自分" in tstr
    best = None                 # 1回の発動につき実況は1行。いちばん大きい成分で書く
    for key, amt, secs in sk.mods:
        if key == "chaos":
            # 知力の比で効き目が変わる。**判定は置かず、量が連続に変わる。**
            hit = [f for f in ([] if ally else tgts) if f.men > 0.0]
            for f in hit:
                r = (u.wits / max(f.wits, 1e-6)) ** CHAOS_WITS
                f.chaos = max(f.chaos, amt * r)
                f.chaos_until = max(f.chaos_until, t + secs)
            if hit:
                m = amt * secs * len(hit)
                if best is None or m > best[3]:
                    best = ("chaos", amt, secs, m)
            continue
        if key == "stun":
            hit = [f for f in ([] if ally else tgts) if f.men > 0.0]
            for f in hit:
                f.effects.append((t + secs, "stun", amt, src))
            if hit:
                m = secs * len(hit) * 10.0
                if best is None or m > best[3]:
                    best = ("stun", 1.0, secs, m)
            continue
        if key == "gauge":      # 旧表記。段差なので値段を持たない（上の注記）
            for f in (tgts if ally else [u]):
                f.gauge += f.gauge_cost * amt
            continue
        dst = (tgts if ally else [u]) if amt > 0.0 else ([] if ally else tgts)
        hit = [f for f in dst if f.men > 0.0]
        for f in hit:
            f.effects.append((t + secs, key, amt, src))
        if hit:
            m = abs(amt) * secs * len(hit)
            if best is None or m > best[3]:
                best = ("buff" if amt > 0.0 else "debuff", amt, secs, m)
    if best is not None:
        say(best[0], best[1], best[2], best[3],
            jp="計略" if kind_jp == "必殺技" else kind_jp)
    if sk.mods:
        _expire(own + foe, t)

    if sk.power <= 0.0 and sk.heal <= 0.0:
        return
    if sk.heal > 0.0:
        # 回復は防御力を通さない（減った兵を戻すだけで、殴られてはいない）。
        amt = HEAL_SCALE * sk.heal * coef / n
        done = 0.0
        for f in tgts:
            if f.men <= 0.0:
                continue
            if sk.dur > 0.0:
                f.overtime.append((t + sk.dur, "heal", amt))
                done += amt * sk.dur
            else:
                # 満タンぶんは実況でも数えない。**スナップショットに対して測る**
                # ので、同じティックで他が撃っていても量が変わらない。
                gain = min(amt, f.men0 - f.men)
                _men_add(f, gain)
                done += gain
        if done > 0.0:
            say("heal", done, sk.dur, mag=done)
        return
    # **兵力に比例しない。** 分母を持たないのが狙い（上の注記）。
    dmg = SKILL_SCALE * sk.power * coef / n
    done = 0.0
    for f in tgts:
        if sk.dur > 0.0:
            # 継続ダメージ。**dmg は既に毎秒の量**（_skill_power が
            # 「威力40%（14秒）」を (0.40, 14.0) と返す）。ここで秒数で割ると
            # 総量が 1/14 になる。実際に踏んだ。
            f.overtime.append((t + sk.dur, "dot", dmg))
            done += dmg
        else:
            take = min(dmg * (100.0 / (100.0 + f.dfn * f.def_mult)), f.men)
            _men_add(f, -take)
            done += take                    # 防御ぶんを引いた実害を出す
    if done > 0.0:
        say("dot" if sk.dur > 0.0 else "damage", done, sk.dur,
            mag=done * (sk.dur or 1.0))
        return


def _fire_skills(own, foe, t: float, ev, seen) -> set:
    """ゲージが消費量に達した札の必殺技を発動する（§7.2）。

    閾値は 100 ではなく**その札の消費ゲージ%**。だから消費50の札は何度も撃ち、
    消費175の札は1戦に1回あるかどうかになる。
    戻り値は**このティックで撃った札の集合**（固有特性の ally_skill 条件が使う）。
    """
    fired = set()
    for u in own:
        if u.men <= 0.0 or not u.skill:
            continue
        need = _skill_threshold(u)
        if u.gauge >= need:
            u.gauge -= need
            u.fires += 1
            fired.add(u)
            if SKILL_SCALE <= 0.0:
                continue
            sk = SKILL_INFO.get(u.skill)
            if not sk:
                continue
            # 同じ技は1戦に1回だけ実況へ出す（3回撃つと同じ行が3本並ぶ）
            show = ev is not None and ("技", u.skill, u.side) not in seen
            if show:
                seen.add(("技", u.skill, u.side))
            _apply_skill(u, sk, SKILL_TARGET.get(u.skill, ""), own, foe, t,
                         src=u.skill, ev=ev if show else None, seen=seen,
                         name=u.skill)
    return fired


def _overtime(units, t: float, dt: float) -> None:
    """時間つきの効果を dt ぶん進める。

    **量に dt を掛けるだけの連続な形にする**（§13「移動の規則に分岐を入れると
    時間刻みに依存する」と同じ理由）。発動時刻の端数で1ティックぶん多く/少なく
    入るのは避けられないが、刻みを細かくすれば消える。
    """
    for u in units:
        if not u.overtime:
            continue
        u.overtime = [e for e in u.overtime if e[0] > t]
        if u.men <= 0.0:
            continue
        for _, kind, per_sec in u.overtime:
            if kind == "heal":
                u.men = min(u.men0, u.men + per_sec * dt)
            else:
                u.men = max(u.men - per_sec * dt
                            * (100.0 / (100.0 + u.dfn * u.def_mult)), 0.0)


def _expire(units, t: float) -> None:
    """持続時間の切れた効果を落として倍率を組み直す。

    §6.6 は効果に秒数を持たせている（遺志は20秒、背水は戦闘終了まで）。
    掛けっぱなしにすると、短い効果と長い効果の区別が消えて価格付けが狂う。
    """
    for u in units:
        if not u.effects:
            continue
        u.effects = [e for e in u.effects if e[0] > t]
        # §6.5 の重複規則。**素朴に足すと壊れる。** 6枚が同じ技を3回ずつ撃つと
        # -10% が18回積まれて -180% になり、相手が完全に無力化される
        # （実測で 攻撃力-10%全体 の値段が 威力200%ダメージ の2.3倍になった）。
        #   同名 … 効果量の大きい方だけを採る（重ねない）
        #   異名 … 同じ能力への補正は加算
        #   上限 … 1つの能力への合計を ±50% に丸める
        best: Dict[Tuple[str, str], float] = {}
        stun = False
        for _, kind, amt, src in u.effects:
            if kind == "stun":
                stun = True
                continue
            k = (kind, src)
            if abs(amt) > abs(best.get(k, 0.0)):
                best[k] = amt
        tot = {"atk": 0.0, "def": 0.0, "spd": 0.0, "rate": 0.0}
        for (kind, _), amt in best.items():
            tot[kind] += amt
        for k in tot:
            tot[k] = min(MOD_CAP, max(-MOD_CAP, tot[k]))
        # 行動阻害は能力補正ではないので ±50% の丸めを受けない（§6.5 は別項）。
        u.atk_mult = 0.0 if stun else 1.0 + tot["atk"]
        u.spd_mult = 0.0 if stun else 1.0 + tot["spd"]
        u.def_mult = 1.0 + tot["def"]
        u.rate_mult = 1.0 + tot["rate"]


def _sight(u: Unit, f: Unit, foes: List[Unit]) -> float:
    """射手 u から的 f への射線の通りやすさ（0〜1）。

    あいだに挟まっている敵の部隊ぶん当たらなくなる。**点と線分の距離**で測るので、
    射手の後ろや的の向こう側にいる札は自動的に外れる（分岐を書かなくてよい）。
    """
    if SIGHT_BLOCK <= 0.0 or u.rng <= 0.0:
        return 1.0
    dx, dy = f.x - u.x, f.y - u.y
    L2 = dx * dx + dy * dy
    if L2 < 1.0:
        return 1.0
    L = math.sqrt(L2)
    block = 0.0
    for b in foes:
        if b is f or b.men <= 0.0:
            continue
        t = ((b.x - u.x) * dx + (b.y - u.y) * dy) / L2
        t = min(max(t, 0.0), 1.0)          # 線分の外へは出さない
        px = u.x + t * dx - b.x
        py = u.y + t * dy - b.y
        # 射線から見た b の見かけの半幅（正面と奥行を射線の向きで混ぜる）
        half = (b.width * abs(dy) + b.depth * abs(dx)) / (2.0 * L)
        block += b.ratio() * smooth_gate(math.hypot(px, py), half, SIGHT_SOFT)
    return math.exp(-SIGHT_BLOCK * block)


def _friendly_fire(u: Unit, own, acc, amount: float) -> None:
    """同士討ち。混乱した札の与ダメージの一部が味方へ向く。

    向き先は**自分以外の味方へ兵力に比例して配る**。誰を撃つかを乱数で選ぶと
    決定論が壊れるうえ、時間刻みで結果が変わる。連続に配れば分岐が要らない。

    減らす先は**通常のダメージと同じ蓄積器**（da / db）。ここで直接 men を
    引くと、同じティックの中で味方の兵力が先に減り、あとから撃つ相手側だけが
    その減った兵力を見る。左右の同時解決が壊れて、同じ編成どうしでも零点が
    0 にならない。
    """
    if amount <= 0.0:
        return
    tot = sum(x.men for x in own if x is not u)
    if tot <= 0.0:
        return
    for k, x in enumerate(own):
        if x is u or x.men <= 0.0:
            continue
        acc[k] += (amount * (x.men / tot)
                   * (100.0 / (100.0 + x.dfn * x.def_mult)))


def chaos_ff(u: Unit) -> float:
    """同士討ちに回る割合。混乱の量で連続に決まる。"""
    return CHAOS_FF * u.chaos / (1.0 + u.chaos) if u.chaos > 0.0 else 0.0


# ============================================================================
# 乱数（§6.4）。**「決定論」は「同じ種なら同じ結果」であって「乱数なし」ではない。**
# ============================================================================
#
# §8.3 が「各部隊戦は独立した乱数シードを持つ」と決めているので、種を渡す形にする。
# `seed=None` なら乱数をまったく引かない（＝これまでの盤面と完全に同じ）。既存の
# 測定はそのまま動き、**構造の非対称を見つける厳密な零点も seed=None のまま残る。**
#
# ── 刻みに依らない引き方にすること ──────────────────────────
#
# 毎ティックのダメージに ±σ を掛けると、1戦の合計のばらつきは σ·√(dt/T) になる。
# **刻みを半分にするとブレが 1/√2 に縮む。** §13 の「時間刻みを振って符号が変わら
# ないものだけを結論に使う」に正面からぶつかるので、この引き方は採らない。
#
# 採るのは2つ。
#
#  勢い（surge）… 部隊ごとの出力が時定数 τ でゆっくり漂う Ornstein-Uhlenbeck 過程。
#    **厳密離散化**で進めるので、刻みを変えても定常分布と自己相関がぴったり保たれる。
#
#        m ← 1 + (m-1)·e^(-dt/τ) + σ·√(1-e^(-2·dt/τ))·N(0,1)
#
#    オイラー近似で書くと刻みの効き方が変わるので、必ずこの形を使うこと。
#
#  技のゆらぎ（jitter）… 必殺技の閾値を発動ごとに ±SKILL_JITTER 振る。**1戦の
#    発動回数は有限で刻みに依らない**ので、これも刻み非依存である。
#
# 幅は §6.4 の「通常ダメージ乱数 ±5%程度」を出発点に、コスト差が勝率へどれだけ
# 残るかを測って決める（§5.3 の目標帯 55〜80%）。
# 幅は15通りのパネルで測って決めた（§7.27）。兵種相性の大きさ 0.85コスト点での
# 勝率が §5.3 の目標帯 55〜80% に収まる最小の値。運の大きさはコスト 0.74点ぶん。
# **単一の対戦で決めないこと。** 1つの噛み合わせで測ると σ=0.10 が 90% と出るが、
# パネルでは 77% で、噛み合わせによって曲線の急さが違う。
RAND_SIGMA = 0.15       # 勢いの定常標準偏差。0 で乱数なし
RAND_TAU = 45.0         # 勢いが戻る時定数（ティック）
# **まだ測っていないので 0 のまま。** つまみは1つずつ入れる。勢いだけで展開は
# 十分ばらけている（決着が 94〜130ティックに散り、壊滅の順序も入れ替わる）。
SKILL_JITTER = 0.00     # 必殺技の閾値のゆらぎ（消費ゲージに対する割合）


def _surge_step(units, dt: float) -> None:
    """勢いを1ティック進める。**厳密離散化**なので刻みで分布が動かない。"""
    if RAND_SIGMA <= 0.0:
        return
    a = math.exp(-dt / RAND_TAU)
    s = RAND_SIGMA * math.sqrt(max(1.0 - a * a, 0.0))
    for u in units:
        if u.rand is None:
            continue
        u.surge = 1.0 + (u.surge - 1.0) * a + s * u.rand.gauss(0.0, 1.0)


def _skill_threshold(u: Unit) -> float:
    """この発動に使う閾値。ゆらぎは**発動ごとに1回**引く（刻みに依らない）。"""
    if SKILL_JITTER <= 0.0 or u.rand is None:
        return u.gauge_cost
    return u.gauge_cost * (1.0 + u.rand.uniform(-SKILL_JITTER, SKILL_JITTER))


def _output(u: Unit) -> float:
    """兵種ごとの時間プロファイル。3兵種で形が違うのが狙い。

      弓兵 … 遠くから撃てるが矢が尽きる（_suppress の AMMO）
      騎兵 … 取り付いた直後が強く、乱戦が続くと落ちる（ここ）
      歩兵 … 増減なし。だから長い乱戦で相対的に強い
    """
    m = u.surge / (1.0 + u.disrupt + u.chaos)   # 受けた混乱ぶん出力が落ちる
    if CHARGE_BONUS > 0.0 and u.typ == CAV:
        m *= 1.0 + CHARGE_BONUS * math.exp(-u.melee / CHARGE_TAU)
    return m


def _suppress(u: Unit, gaps: List[float]) -> float:
    """接敵抑制。射程を持つ札は、敵に近づかれるほど出力が落ちる。

    これがないと弓は密着されても撃ち続け、騎兵が突っ込む意味がなくなる。実測では
    騎兵→弓兵が 0.0%（＝弓兵が騎兵に必ず勝つ）から動かなかった。
    最近接の敵までの距離だけで決まる連続な形にしてあり、分岐を含まない。
    """
    if u.rng <= 0.0 or not gaps:
        return 1.0
    sup = 1.0 - SUPPRESS_MAX * smooth_gate(min(gaps), 0.0, SUPPRESS_R)
    if AMMO_MODE == "attrition":
        if AMMO_SPAN > 0.0 and u.shot > AMMO_SPAN:
            sup *= math.exp(-(u.shot - AMMO_SPAN) / AMMO_TAIL_P)
    elif AMMO_TIME > 0.0 and u.shot > AMMO_TIME:
        sup *= math.exp(-(u.shot - AMMO_TIME) / AMMO_TAIL)
    return sup


def simulate(a: Army, b: Army, dt: float = 0.25, t_max: float = T_MAX,
             repulse: float = 0.0, damage: bool = True,
             events: "List[Event] | None" = None,
             seed: "int | None" = None) -> Dict:
    """events を渡すと出来事を記録する。**記録は読み取り専用**で、勝敗にも
    測定にも一切影響しない（§9.3。§8.2 の引き分け帯を測定へ持ち込んで計器を
    殺した失敗と同じ形を避けるため）。

    seed を渡すと乱数が入る（§6.4）。**渡さなければ1つも引かない**ので、
    これまでの測定はそのまま同じ値を出す。種は部隊ごとに (seed, side, 番号) から
    導くので、同じ種なら何度走らせても同じ結果になる（§8.4 の再現性）。

    **同じ編成どうしでも、種を入れれば結果は五分にならない。** それが乱数を
    入れた意味であって、壊れているのではない。構造の非対称を見つける厳密な
    零点は `seed=None` のまま残してある。
    """
    # 陣形相性（表で決める）。循環で勝っている側の与ダメージへ掛ける。
    dr = (a.rank - b.rank) % 3
    fa = 1.0 + FORM_BONUS if dr == 2 else 1.0
    fb = 1.0 + FORM_BONUS if dr == 1 else 1.0

    # 兵種相性は**コスト点**で与える（TYPE_EDGE_COST）。
    #
    # ダメージへ % で掛けると、同じ % でも編成によって受け取る価値が違うため
    # 推移成分（単にどれかが強い）が混ざる。実測では補正を上げるほど推移幅が
    # 0.005 → 1.319 と育った。バランスの目標と同じ単位（コスト点）で与えると
    # 価値が編成によらず揃う。総コスト 30 に対する加算として効かせる。
    te = type_edge(a, b)     # すでにコスト点の単位（表の係数込み）
    ka = 1.0 + te / 30.0
    kb = 1.0 - te / 30.0

    ua = build(a, +1, ka)
    ub = build(b, -1, kb)
    if seed is not None and (RAND_SIGMA > 0.0 or SKILL_JITTER > 0.0):
        # **部隊ごとに独立の流れを持たせる。** 1本の流れを共有すると、引く順序が
        # 変わるだけで結果が動き、処理順の入れ替えに弱くなる。
        for _side, _us in ((1, ua), (-1, ub)):
            for _i, _u in enumerate(_us):
                _u.rand = random.Random("{}/{}/{}".format(seed, _side, _i))
    _plan_paths(ua, ub, a.form, b.form)
    _plan_paths(ub, ua, b.form, a.form)

    seen = set()
    retired = {"all": set(), "new": set()}
    y0a = sum(u.y for u in ua) / len(ua)
    y0b = sum(u.y for u in ub) / len(ub)
    if events is not None:
        _log_open(events, seen, a, b, ua, ub)

    start_width = _front_width(ua)
    t = 0.0
    steps = int(round(t_max / dt))
    reason = "time"
    na, nb = len(ua), len(ub)
    men0a = sum(u.men0 for u in ua)
    men0b = sum(u.men0 for u in ub)

    for _ in range(steps):
        # --- 距離は1回だけ作り、移動の制動と射撃の両方で使う ----------------
        gap = [[box_gap(x, y) for y in ub] for x in ua]

        # --- 移動（両軍を同時に評価してから同時に反映する） -----------------
        newpos = []
        for i, u in enumerate(ua):
            newpos.append((u, _step_progress(u, ub, gap[i], dt)))
        for j, u in enumerate(ub):
            newpos.append((u, _step_progress(u, ua, [gap[i][j] for i in range(na)], dt)))
        for u, s in newpos:
            u.progress = s
            u.x, u.y = u.pos_at(s)

        if repulse > 0.0:
            _legacy_repulse(ua + ub, dt, repulse)

        # --- 射撃（同時解決。片側を先に処理すると左右非対称になる） ---------
        if damage:
            ramp = damage_ramp(t)
            ta = tb = 1.0
            if TAPER > 0.0:
                ra_ = max(sum(u.men for u in ua) / men0a, 1e-6)
                rb_ = max(sum(u.men for u in ub) / men0b, 1e-6)
                ta = (rb_ / ra_) ** TAPER
                tb = (ra_ / rb_) ** TAPER
            # 矢の消費。
            #
            # volley: **自分が実際に撃った量**で数える。矢を減らすのは射撃であって
            # 時計でも敵の損耗でもない。射撃量は自分の兵力に比例するので、半壊した
            # 部隊は撃つ量も矢の減りも半分になる。attrition では敵の損耗に紐づけて
            # いたため、撃つ量が半分でも矢は満額で減っていた（物理的に不整合）。
            if AMMO_MODE == "volley":
                for x in ua + ub:
                    if x.rng > 0.0 and x.men0 > 0.0:
                        x.shot += (x.men / x.men0) * dt
            elif AMMO_MODE == "attrition":
                # **単調増加（ラチェット）にする。** 現在値をそのまま代入すると、
                # 敵が回復したときに比が下がって**消費済みの矢が戻る**。矢は戻らない。
                # 回復を実装したときに静かに壊れる形なので、ここで止めておく。
                wa = 1.0 - sum(y.men for y in ub) / men0b
                wb = 1.0 - sum(y.men for y in ua) / men0a
                for x in ua:
                    x.shot = max(x.shot, wa)
                for x in ub:
                    x.shot = max(x.shot, wb)
            else:
                for x in ua + ub:
                    if AMMO_TIME > 0.0 and x.rng > 0.0 and x.men > 0.0:
                        x.shot += dt
            # **減衰は矢の消費と無関係。** ここは以前 else: の中に、しかも for を
            # 抜けた位置に置かれていて、最後の1部隊にしか当たらず、いまの
            # AMMO_MODE では一度も走っていなかった。混乱の秒数が効かない形。
            _surge_step(ua + ub, dt)
            for x in ua + ub:
                if x.disrupt > 0.0:
                    x.disrupt *= math.exp(-dt / DISRUPT_TAU)
                if x.chaos > 0.0 and t + dt >= x.chaos_until:
                    x.chaos = 0.0
            if CHARGE_BONUS > 0.0:
                for i, x in enumerate(ua):
                    if min(gap[i]) <= 1.0:
                        x.melee += dt
                for j, x in enumerate(ub):
                    if min(gap[i][j] for i in range(na)) <= 1.0:
                        x.melee += dt
            da = [0.0] * na
            db = [0.0] * nb
            for i, u in enumerate(ua):
                ws = _weights(u, ub, gap[i])
                tot = sum(ws)
                if tot <= 1e-12:
                    continue
                gate = max(ws)
                base = (u.men * LETHALITY * (u.atk * u.atk_mult / BASE_ATK)
                        / u.interval * gate / tot * dt
                        * _suppress(u, gap[i]) * _output(u) * fa * ramp * ta)
                ff = chaos_ff(u)
                if ff > 0.0:
                    _friendly_fire(u, ua, da, base * ff)
                    base *= 1.0 - ff
                for j, (f, w) in enumerate(zip(ub, ws)):
                    if w <= 0.0:
                        continue
                    hit = base * w * (100.0 / (100.0 + f.dfn * f.def_mult))
                    if TRAITS_ON and _vs_faction(u, f):
                        hit *= 1.0 + VS_FACTION      # 対勢力（常在型）
                    if u.typ == ARC and ARC_LETHAL < 1.0:
                        f.disrupt += (1.0 - ARC_LETHAL) * hit / f.men0 * DISRUPT_GAIN
                        hit *= ARC_LETHAL
                    if SKILLS_ON and f.men0 > 0:
                        u.gauge += hit / f.men0 * GAUGE_PER_DEAL
                    db[j] += hit
            if SEQUENTIAL_DAMAGE:      # 陽性対照。通常は通らない
                for u, d in zip(ub, db):
                    u.men = max(u.men - d, 0.0)
                db = [0.0] * nb
            for j, u in enumerate(ub):
                col = [gap[i][j] for i in range(na)]
                ws = _weights(u, ua, col)
                tot = sum(ws)
                if tot <= 1e-12:
                    continue
                gate = max(ws)
                base = (u.men * LETHALITY * (u.atk * u.atk_mult / BASE_ATK)
                        / u.interval * gate / tot * dt
                        * _suppress(u, col) * _output(u) * fb * ramp * tb)
                ff = chaos_ff(u)
                if ff > 0.0:
                    _friendly_fire(u, ub, db, base * ff)
                    base *= 1.0 - ff
                for i, (f, w) in enumerate(zip(ua, ws)):
                    if w <= 0.0:
                        continue
                    hit = base * w * (100.0 / (100.0 + f.dfn * f.def_mult))
                    if TRAITS_ON and _vs_faction(u, f):
                        hit *= 1.0 + VS_FACTION      # 対勢力（常在型）
                    if u.typ == ARC and ARC_LETHAL < 1.0:
                        f.disrupt += (1.0 - ARC_LETHAL) * hit / f.men0 * DISRUPT_GAIN
                        hit *= ARC_LETHAL
                    if SKILLS_ON and f.men0 > 0:
                        u.gauge += hit / f.men0 * GAUGE_PER_DEAL
                    da[i] += hit
            for u, d in zip(ua, da):
                u.men = max(u.men - d, 0.0)
            for u, d in zip(ub, db):
                u.men = max(u.men - d, 0.0)

        # **必殺技を先に、固有特性を後に。** 特性の ally_skill 条件は「味方が
        # 技を撃った」を見るので、順序を逆にすると1ティック遅れる。
        fired = set()
        if SKILLS_ON:
            for x, taken in ((u, d) for u, d in zip(ua, da)):
                x.gauge += GAUGE_PER_SEC * x_rate(x) * dt
                if x.men0 > 0:
                    x.gauge += taken / x.men0 * GAUGE_PER_TAKE
            for x, taken in ((u, d) for u, d in zip(ub, db)):
                x.gauge += GAUGE_PER_SEC * x_rate(x) * dt
                if x.men0 > 0:
                    x.gauge += taken / x.men0 * GAUGE_PER_TAKE
            _open_men_window()
            fired = _fire_skills(ua, ub, t + dt, events, seen)
            fired |= _fire_skills(ub, ua, t + dt, events, seen)

        if TRAITS_ON:
            newly = {u for u in ua + ub
                     if u.ratio() < TRAIT_TRIGGER and u not in retired["all"]}
            if newly:
                retired["new"] = newly
                retired["all"] |= newly
            else:
                retired["new"] = set()
            _fire_traits(ua, ub, t + dt, retired, events, seen, fired)

        # **技と特性を撃ち終えてから、まとめて兵力へ反映する。**
        if SKILLS_ON or TRAITS_ON:
            _flush_men()

        if SKILLS_ON or TRAITS_ON:
            _expire(ua + ub, t + dt)
            # **発動より後に進める。** 先に進めると、いま乗った継続効果が
            # 同じティックで1回ぶん入ってしまう。
            _overtime(ua + ub, t + dt, dt)

        t += dt
        ra = sum(u.men for u in ua) / men0a
        rb = sum(u.men for u in ub) / men0b
        if events is not None:
            _log_tick(events, seen, t, ua, ub, gap)
        if ra < ROUT_RATIO or rb < ROUT_RATIO:
            reason = "rout"
            if events is not None:
                lo, hi = (("A", ra), ("B", rb)) if ra < rb else (("B", rb), ("A", ra))
                events.append(Event(t, "決着", 1,
                    "{}軍、残存{:.0f}%を割って潰走。{}軍の勝利。".format(
                        _JP[lo[0]], ROUT_RATIO * 100, _JP[hi[0]])))
            break

    ra = sum(u.men for u in ua) / men0a
    rb = sum(u.men for u in ub) / men0b
    if events is not None:
        _log_close(events, seen, t, reason, ua, ub, ra, rb)
    diff = ra - rb
    if GROUND_WEIGHT > 0.0:
        # 押し込み。A は +y へ、B は -y へ進むのが前進。
        push_a = (sum(u.y for u in ua) / len(ua)) - y0a
        push_b = y0b - (sum(u.y for u in ub) / len(ub))
        diff += GROUND_WEIGHT * (push_a - push_b) / BOARD_D
    score = 0.5 if abs(diff) < DRAW_BAND else (1.0 if diff > 0 else 0.0)
    return {"score": score, "diff": diff, "ra": ra, "rb": rb, "t": t,
            "reason": reason,
            "width_start": start_width, "width_end": _front_width(ua),
            "fires_a": [(u.name or u.typ, u.fires) for u in ua],
            "fires_b": [(u.name or u.typ, u.fires) for u in ub],
            # 固有特性の発動回数と、潰走した札の数。**特性の測定はここを先に見る。**
            # 誘発条件の多くは「味方が潰走した」なので、誰も潰走しない対戦では
            # どんな特性も 0.0000 になる（実測で7種が該当した）。
            "traits_a": sum(u.fired for u in ua),
            "traits_b": sum(u.fired for u in ub),
            "routed_a": sum(1 for u in ua if u.ratio() < ROUT_UNIT),
            "routed_b": sum(1 for u in ub if u.ratio() < ROUT_UNIT)}


def _step_progress(u: Unit, foes: List[Unit], gaps: List[float],
                   dt: float) -> float:
    if u.total_len <= 1e-9:
        return 0.0
    # ZOC は「敵を**通り過ぎる**動き」にだけ課す。取り付く動きに同じだけ課すと、
    # 迂回を高くする前に正面の接敵が死ぬ（実測: ZOC_STR=1.6 で歩兵の到達 12%、
    # 誰も接敵できず残存 1.000 のまま時間切れ）。迂回の度合い detour は
    # _plan_paths が敵前衛と後衛の硬さの比から連続に決めており、分岐を含まない。
    z = 0.0
    if u.detour > 0.0:
        for f, d in zip(foes, gaps):
            z += ZOC_STR * f.ratio() * smooth_gate(d, 0.0, ZOC_R)
        z *= u.detour
    v = u.speed * u.spd_mult * math.exp(-z)
    remain = u.total_len - u.progress
    return u.total_len - approach_exact(remain, v, dt)


def _front_width(units: Sequence[Unit]) -> float:
    """前衛の左右端の中心間距離。戦列がどれだけ広がったかを測る。

    前衛か後衛かは**開戦時の枠**で決める。現在の y で分類すると、前進した札が
    途中で別の分類へ移り、広がりではなく分類の変化を測ってしまう（計器の罠）。
    迂回する騎兵は横へ大きく出るのが仕事なので、この指標からは外す。
    """
    fr = [u for u in units if u.is_front and u.typ != CAV]
    if len(fr) < 2:
        fr = [u for u in units if u.is_front]
    if len(fr) < 2:
        fr = list(units)
    xs = [u.x for u in fr]
    return max(xs) - min(xs)


def _legacy_repulse(units: List[Unit], dt: float, strength: float) -> None:
    """【旧実装の再現】対斥力を陽的オイラーで積分する。

    直すためではなく、症状を測って再現できるようにするために残している。
    """
    for a in units:
        fx = 0.0
        for b in units:
            if a is b:
                continue
            dx = a.x - b.x
            dy = a.y - b.y
            d2 = dx * dx + dy * dy
            if d2 < 1e-9:
                continue
            d = math.sqrt(d2)
            reach = (a.width + b.width) / 2.0 * LEGACY_REACH
            if d < reach:
                fx += strength * (reach - d) / reach * (dx / d)
        a.x += fx * dt


