#   条件          弓係数  跳び幅        （弓係数の順に並べたもの）
#   時間 25秒      0.697  1.58倍
#   射撃量 25      0.725  1.55倍
#   消耗割合 0.20  0.764  1.58倍
#   時間 40秒      0.835  2.01倍
#   射撃量 40      0.870  1.93倍
#   時間 55秒      0.969  2.50倍
#   消耗割合 0.30  0.982  1.95倍   ← 弓係数がほぼ同じなのに跳び幅が 0.5 小さい
