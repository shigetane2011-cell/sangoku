def _army_name(army: "Army", fallback: str) -> str:
    c = Counter(x.faction for x in army.cards if x.faction)
    return c.most_common(1)[0][0] if c else fallback

# 種類ごとの行数上限（§9.3）。合流したぶんは1行として数える。
# **打撃と計略を別の種類にする。** 同じ「必殺技」に混ぜると、行の取り合いで
# 補助技が勝ってダメージ技が一行も出なくなる（実測: 火計も無双乱舞も消えた）。
# 大きさの単位が違うもの（人数 と %×秒×枚数）を1つの物差しで比べていたのが原因で、
# 係数を調整して釣り合わせるより、枠を分けるほうが素直である。
LINE_CAPS = {"布陣": 1, "予告": 2, "結果": 2, "接敵": 1, "抑制": 1,
             "必殺技": 2, "計略": 2, "誘発": 2, "突撃": 1, "壊滅": 2, "決着": 1,
             "時刻": 1}
# 優先順位（小さいほど先に確保する）
LINE_PRIO = {"決着": 1, "予告": 2, "結果": 2, "必殺技": 3, "計略": 3, "誘発": 3,
             "突撃": 4, "壊滅": 4, "時刻": 4, "接敵": 5, "抑制": 6, "布陣": 7}
LINE_BUDGET = 12
ROUT_UNIT = 0.15        # 一枚が「壊滅」と見なされる残存率（表示のみ）
SUPPRESS_SHOW = 0.87    # 抑制がこの値を下回ったら1行にする（表示のみ）
# 実況の時間表現。**盤面の1ティックを戦場の 1.35 分として読ませる。**
#
# 盤面の時間はティックの単位であって、戦場で流れた時間ではない。**尺は表示だけの
# 量なので、盤面の較正には一切触れない**（T_MAX を動かすと相性も値付けも全部
# 測り直しになる。動かすのはこちらの尺のほうである）。
#
#   開戦 8:00 ／ 上限 400ティック × 1.35 = 540分 → 17:00 ちょうど
#   中央値 137ティックの戦闘は 185分＝「3時間5分の戦い」
#
# 以前は 6時開始・1ティック＝1分で、上限まで戦っても 12:40 にしかならず、日没まで
# 届かなかった（だから「日没」と書けなかった）。朝に始めて夕刻に決着がつく尺へ
# 直したので、夜戦・払暁・日没の表現はこの上に載せられる。
#
# **1分ちょうどでなくなったので、秒数をそのまま分として書けない。** 「毎秒317人」を
# 「毎分317人」と読み替える手は使えず、持続時間は mins()、率は per_min() を通す。
# 刻み（dt）を変えても表示は変わらない。
BATTLE_START_H = 8      # 開戦の時刻（時）
BATTLE_START_M = 0      # 同（分）
MIN_PER_TICK = 1.35     # 盤面1ティックを戦場の何分として読ませるか（表示のみ）

# 時刻帯の行（§9.3）。**`narrate()` の中だけで作る。`simulate()` は時刻帯を知らない。**
# 盤面へ入れないので、表示専用であることが構造で保証される（勝敗にも測定にも
# 触れようがない）。実カード144対戦で測った決着時刻の分布に合わせてある:
#
#   中央値 11:10 ／ 08-10時 5% ／ 10-12時 64% ／ 12-14時 17%
#   14-16時 6% ／ 16-17時 1% ／ 上限（日没）到達 7%
#
# **7割の戦いは昼前に終わる。** だから昼までの帯には行を置かない。置いても
# 「朝である」としか言っておらず、開始時刻が固定なので情報が無い。時刻帯が
# 意味を持つのは「長引いている」ことを語るときだけなので、正午から先に置く。
DAY_BANDS = [(12 * 60, "日が高くなる。両軍とも退かぬまま、戦いは昼へ入る。"),
             (14 * 60, "日が傾きはじめる。土埃が斜めの光の中に立つ。"),
             (16 * 60, "西日が長い影を落とす。日没が近い。")]
# 帯をまたいだ直後に決着がつく戦いには、その帯の行を出さない（表示分）。
# **帯は本質的に崖である**（11:59 と 12:01 で読み味が変わる）。盤面には効かないが、
# 「昼へ入る」と書いた次の行が決着では嘘になるので、決着までの余裕で抑える。
DAY_BAND_MARGIN = 20.0
# **1戦に1本だけ、いちばん遅い帯を採る**（LINE_CAPS の「時刻」＝1／`mag` に帯の
# 時刻を入れて後の帯を優先）。最初は早い帯から採っていたが、実カード144対戦で
# 12時の行が19%出るだけで、**14時と16時が一度も出なかった**。行の予算に押し出されて
# いたためで、いちばん情報のある帯（夕方までもつれている）が飢えていた。
# 16時まで戦った戦いに要るのは「昼へ入る」ではなく「日没が近い」である。


def mins(secs: float) -> float:
    """盤面の秒数を戦場の分へ直す（表示のみ）。"""
    return secs * MIN_PER_TICK


def per_min(per_sec: float) -> float:
    """盤面の毎秒あたりの量を、戦場の毎分あたりへ直す（表示のみ）。"""
    return per_sec / MIN_PER_TICK


def clock(t: float) -> str:
    """盤面の経過（ティック）を戦場の時刻（24時間表記）へ直す。"""
    m = BATTLE_START_H * 60 + BATTLE_START_M + int(mins(t))
    return "{:02d}:{:02d}".format((m // 60) % 24, m % 60)
# 実況に出す下限。対象の兵力に対してこれ未満のダメージ・回復は行にしない。
NARRATE_FLOOR = 0.02
# これ以上の迂回だけを賭けとして予告する（表示のみ）。
# **0.25 では1戦も出なかった。** 実カード12戦の迂回は最大 0.237、平均 0.015 で、
# 合成カードでも 0.234 止まり。§9.3 が唯一の演出装置と決めた「予告と結果」の対が
# まるごと死んでいた。迂回そのものは連続量として効いているので、崖ではなく
# 表示の閾値の置き方の問題である。0.12 へ下げる。
DETOUR_SHOW = 0.12


@dataclass
class Event:
    t: float
    kind: str
    prio: int
    text: str
    # 出来事の大きさ（人数など）。**行を選ぶときに種類の中での順位を決める。**
    # 必殺技は1戦に18回ほど飛ぶので、先に起きたものから採ると小物ばかり並ぶ。
    mag: float = 0.0


def _wing(u: Unit) -> str:
    x = u.x0 * u.side          # 自軍から見た左右
    return "左翼" if x < -1.0 else ("右翼" if x > 1.0 else "中央")


def _who(u: Unit) -> str:
    """札の呼び名。実カードなら武将名、合成カードなら位置と兵種で呼ぶ。"""
    if u.name:
        return u.name
    return "{}軍{}{}の{}".format(_JP["A" if u.side > 0 else "B"], _wing(u),
                                 "前衛" if u.is_front else "後衛", TYPE_JP[u.typ])


def _log_open(ev, seen, a: Army, b: Army, ua, ub) -> None:
    _JP["A"] = _army_name(a, "曹")
    _JP["B"] = _army_name(b, "孫")
    if _JP["A"] == _JP["B"]:            # 同勢力どうしは区別が付かないので添字
        _JP["A"], _JP["B"] = _JP["A"] + "(先)", _JP["B"] + "(後)"
    def shape(army: Army) -> str:
        return {2: "狭く深い", 3: "標準", 4: "広く浅い"}.get(
            army.form.n_front, f"前衛{army.form.n_front}枚")
    def mix(army: Army) -> str:
        c = {}
        for card in army.cards:
            c[card.typ] = c.get(card.typ, 0) + 1
        return "・".join(f"{TYPE_JP[t]}{c[t]}" for t in TYPES if c.get(t))
    # 布陣は時刻を持たない（t = -1）。合流させず必ず先頭に置く。
    line = "{}軍は{}（{}）、{}軍は{}（{}）。".format(
        _JP["A"], shape(a), mix(a), _JP["B"], shape(b), mix(b))
    # 常在型はタイムラインに瞬間を持たないので、ここで触れる（§9.3）
    for side, us in (("A", ua), ("B", ub)):
        vg = [u.name for u in us if u.name and u.trait == "vanguard" and u.is_front]
        if vg:
            line += "{}軍は{}が陣頭。".format(_JP[side], "・".join(vg))
    ev.append(Event(-1.0, "布陣", LINE_PRIO["布陣"], line))
    # 迂回の予告。所要時間も捨てる攻撃量も経路長から確定している（§9.3）
    bets = [u for u in list(ua) + list(ub)
            if u.typ == CAV and u.detour > DETOUR_SHOW and u.total_len > 1.0]
    bets.sort(key=lambda u: -u.total_len)
    seen_side = set()
    for u in bets:                      # 同じ側から2本続けない
        if u.side in seen_side:
            continue
        seen_side.add(u.side)
        # **予告した札だけを賭けとして印を付ける。** 結果はこの札についてだけ
        # 語る。予告と結果が対にならないと、setup のない payoff や payoff の
        # ない setup が出て演出装置が壊れる（実測で両方出た）。
        seen.add(("賭", id(u)))
        ev.append(Event(0.0, "予告", LINE_PRIO["予告"],
            "{}、戦列を離れて大きく回り込む。{:.0f}mの迂回、"
            "およそ{:.0f}分ぶんの攻撃を捨てる賭け。".format(
                _who(u), u.total_len, mins(u.total_len / u.speed))))


def _log_tick(ev, seen, t, ua, ub, gap) -> None:
    # 接敵。**正面の重なりが最も大きい組**を報じる。
    #
    # 縁の距離で選ぶと、500m幅の方陣どうしが角で触れただけの組を「正面から
    # 噛み合う」と報じてしまう（実測で縁0.13m・中心451m離れた組が選ばれた）。
    # 重なりが 0 なら、それは正面ではなく側面が触れているだけである。
    if "接敵" not in seen:
        best = None
        for x in ua:
            if not x.is_front:
                continue
            for y in ub:
                if not y.is_front:
                    continue
                ov = min(x.x + x.width / 2, y.x + y.width / 2) - \
                     max(x.x - x.width / 2, y.x - y.width / 2)
                d = box_gap(x, y)
                key = (-max(ov, 0.0), d)
                if best is None or key < best[0]:
                    best = (key, x, y, max(ov, 0.0), d)
        if best is not None and best[4] <= 1.0:
            seen.add("接敵")
            n = sum(1 for x in ua if x.is_front
                    for y in ub if y.is_front and box_gap(x, y) <= 1.0)
            if best[3] > 1.0:
                ev.append(Event(t, "接敵", LINE_PRIO["接敵"],
                    "両軍前衛が接触。{}と{}が正面{:.0f}mで噛み合う"
                    "（{}組が交戦）。".format(
                        _who(best[1]), _who(best[2]), best[3], n)))
            else:
                ev.append(Event(t, "接敵", LINE_PRIO["接敵"],
                    "{}が前進し、{}の側面に取り付く。正面で受ける敵がいない"
                    "（{}組が交戦）。".format(
                        _who(best[1]), _who(best[2]), n)))
    # 迂回の到達
    for u in list(ua) + list(ub):
        k = ("着", id(u))
        if k in seen or ("賭", id(u)) not in seen:
            continue
        if u.progress / u.total_len > 0.97:
            seen.add(k)
            foes = ub if u.side > 0 else ua
            tgt = min((f for f in foes if not f.is_front),
                      key=lambda f: math.hypot(f.x - u.x, f.y - u.y), default=None)
            ev.append(Event(t, "結果", LINE_PRIO["結果"],
                "{}が敵後衛に到達（{:.0f}分を要した）。{}の側背を突く。"
                "この時点で残り{:.0f}%。".format(
                    _who(u), mins(t), _who(tgt) if tgt else "後衛",
                    100 * tgt.ratio() if tgt else 0)))
    # 騎兵が突撃の勢いを使い切る（乱戦に呑まれる）
    if CHARGE_BONUS > 0.0:
        for u in list(ua) + list(ub):
            k = ("突", id(u))
            # 勢いがほぼ抜けた時点で報じる。CHARGE_TAU で切ると出力がまだ122%
            # あり「勢いを失い」と書くのが嘘になる。落差で語る。
            if (k not in seen and u.typ == CAV and u.men > 0.0
                    and u.melee > 2.5 * CHARGE_TAU):
                seen.add(k)
                ev.append(Event(t, "突撃", LINE_PRIO["突撃"],
                    "{}、突撃の勢いが尽きて乱戦へ（{:.0f}% → {:.0f}%）。".format(
                        _who(u), 100 * (1.0 + CHARGE_BONUS), 100 * _output(u))))
    # 弓の抑制
    for units, foes, idx in ((ua, ub, lambda i, j: gap[i][j]),
                             (ub, ua, lambda i, j: gap[j][i])):
        for i, u in enumerate(units):
            if u.typ != ARC or ("抑", id(u)) in seen:
                continue
            g = [idx(i, j) for j in range(len(foes))]
            sup = _suppress(u, g)
            if sup < SUPPRESS_SHOW:
                seen.add(("抑", id(u)))
                near = min(foes, key=lambda f: math.hypot(f.x - u.x, f.y - u.y))
                ev.append(Event(t, "抑制", LINE_PRIO["抑制"],
                    "{}、{}に{:.0f}mまで詰められ斉射が鈍る（威力{:.0f}%）。".format(
                        _who(u), _who(near), min(g), 100 * sup)))
    # 壊滅
    for u in list(ua) + list(ub):
        k = ("滅", id(u))
        if k not in seen and u.ratio() < ROUT_UNIT:
            seen.add(k)
            own = ua if u.side > 0 else ub
            rest = sum(x.men for x in own) / sum(x.men0 for x in own)
            ev.append(Event(t, "壊滅", LINE_PRIO["壊滅"],
                "{}が壊滅（{:,.0f}人を失う）。{}軍は残り{:.0f}%。".format(
                    _who(u), u.men0 - u.men,
                    _JP["A" if u.side > 0 else "B"], 100 * rest)))


def _log_close(ev, seen_bets, t, reason, ua, ub, ra, rb) -> None:
    if reason != "time":
        return
    # 賭けの結果は必ず語る。届かなかった側も拾う。
    for u in list(ua) + list(ub):
        if (("賭", id(u)) in seen_bets
                and u.progress / u.total_len <= 0.97):
            ev.append(Event(t, "結果", LINE_PRIO["結果"],
                "{}は敵後衛へ回り込めないまま終わる（行程{:.0f}%、"
                "残り{:.0f}m）。".format(
                    _who(u), 100 * u.progress / u.total_len,
                    u.total_len - u.progress)))
    lost_a = sum(u.men0 - u.men for u in ua)
    lost_b = sum(u.men0 - u.men for u in ub)
    win = "A" if ra > rb else "B"
    ev.append(Event(t, "決着", LINE_PRIO["決着"],
        "日没。決着つかず、両軍とも兵を退く。{}軍{:.0f}%（{:,.0f}人損失）対"
        "{}軍{:.0f}%（{:,.0f}人損失）で、"
        "{}軍の勝利。".format(_JP["A"], 100 * ra, lost_a,
                             _JP["B"], 100 * rb, lost_b, _JP[win])))


def narrate(a: Army, b: Army, dt: float = 0.25,
            seed: "int | None" = None) -> List[str]:
    """1部隊戦の実況行を返す。8〜12行（§9.3）。

    **種は必ず本番と同じものを渡すこと。** 渡さないと乱数の無い戦いを語ることに
    なり、実況が「実際に起きた戦い」と別物になる（§8.4 はリプレイを戦闘イベント
    ログの正とすると決めている）。
    """
    ev: List[Event] = []
    simulate(a, b, dt=dt, events=ev, seed=seed)

    # 時刻帯の行を**ここで合成する**。盤面から受け取るのではなく、終わった戦いの
    # 長さだけを見て足す。決着の直前に帯をまたいだ場合は出さない（DAY_BAND_MARGIN）。
    t_end = max((e.t for e in ev), default=0.0)
    start = BATTLE_START_H * 60 + BATTLE_START_M
    for at, text in DAY_BANDS:
        tt = (at - start) / MIN_PER_TICK
        if tt > 0.0 and mins(t_end - tt) >= DAY_BAND_MARGIN:
            ev.append(Event(tt, "時刻", LINE_PRIO["時刻"], text, mag=float(at)))

    # 種類ごとの上限と全体の予算で絞る。**大きさではなく種類で選ぶ。**
    # 種類の優先順（§9.3）→ 同じ種類なら大きい順 → 同着なら早い順
    ev.sort(key=lambda e: (e.prio, -e.mag, e.t))
    # 布陣と決着は枠に関係なく必ず出す。**予算で落ちると誰と誰の話か分からなくなる**
    # （実測で虎牢関の布陣行が消えた）。優先順位が低いのは「先に確保しない」という
    # 意味であって、「無くてよい」ではない。
    kept = [e for e in ev if e.kind in ("布陣", "決着")][:2]
    used = {e.kind: 1 for e in kept}
    for e in ev:
        if e in kept:
            continue
        if used.get(e.kind, 0) >= LINE_CAPS.get(e.kind, 1):
            continue
        if len(kept) >= LINE_BUDGET:
            break
        used[e.kind] = used.get(e.kind, 0) + 1
        kept.append(e)

    # 挿絵を差す場所を決める（§9.3 の三幕）。序＝布陣、破＝いちばん大きい出来事、
    # 急＝決着。**大きさで選ぶのは「破」だけ**で、序と急は位置で決まっている。
    mid = [e for e in kept if e.kind in ("必殺技", "計略", "誘発", "壊滅")]
    art = {id(e) for e in kept if e.kind in ("布陣", "決着")}
    if mid:
        art.add(id(max(mid, key=lambda e: e.mag)))

    # 同じ秒の出来事は1行へ合流させる（布陣は t=-1 なので合流しない）
    kept.sort(key=lambda e: (e.t, e.prio))
    out, i = [], 0
    while i < len(kept):
        same = [kept[i]]
        while (i + 1 < len(kept) and kept[i + 1].t >= 0.0
               and int(kept[i + 1].t) == int(kept[i].t)):
            i += 1
            same.append(kept[i])
        head = "【布陣】" if same[0].t < 0.0 else "【{}】".format(clock(same[0].t))
        mark = "◆" if any(id(e) in art for e in same) else "　"
        out.append(mark + head + " " + " ".join(e.text for e in same))
        i += 1
    return out


