    pairs = [(INF, CAV, 0, 1, "歩→騎"), (CAV, ARC, 1, 2, "騎→弓"),
             (ARC, INF, 2, 0, "弓→歩")]
    target = args.target
    print(f"兵種相性の表の較正（目標 各方向 +{target:.2f} コスト点"
          f"／必殺技 {'オン' if SKILLS_ON else 'オフ'}）")
    print()
    for it in range(4):
        M, r, _ = type_table(args.dt, args.rot)
        cur = [M[(i, j)] for _, _, i, j, _ in pairs]
        print("  反復{}  ".format(it)
              + "  ".join("{} {:+.3f}".format(n, v)
                          for (_, _, _, _, n), v in zip(pairs, cur))
              + "   推移幅 {:.3f}".format(max(r) - min(r)))
        if max(abs(v - target) for v in cur) < 0.05:
            break
        for (ti, tj, i, j, _), v in zip(pairs, cur):
            k = TYPE_EDGE_COST[(ti, tj)]
            TYPE_EDGE_COST[(ti, tj)] = k + 0.5
            M2, _, _ = type_table(args.dt, args.rot)
