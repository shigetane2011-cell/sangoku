def yardstick(dt: float = 0.5) -> float:
    """総コスト1点あたり、残存兵力率の差がいくつ動くか。"""
    base = flat_army()
    pts = [(e, margin(flat_army(cost=BASE_COST + e / 6.0), base, dt))
           for e in (0.3, 0.6, 1.2, 3.0, 6.0)]
    return sum(x * y for x, y in pts) / sum(x * x for x, _ in pts)


def matchup_cost(a: Army, b: Army, slope: float, dt: float = 0.5,
                 rot: int = 6) -> float:
    """編成 a の b に対する優位を**コスト点**で返す。

    枠の並びを回して多数の局面を作り、左右を入れ替えて反対称化する。左右の偏りは
    定義上打ち消えるので、残るのは中身の差だけになる。勝率は使わない
    （総コスト +0.1点で 100% に飽和するため。`cmd_triangle` の較正を参照）。
    """
    tot = 0.0
    n = 0
    for r in range(rot):
        ar = Army(a.cards[r:] + a.cards[:r], a.form)
        for t in range(rot):
            br = Army(b.cards[t:] + b.cards[:t], b.form)
            tot += (margin(ar, br, dt) - margin(br, ar, dt)) / 2.0
            n += 1
    return (tot / n) / slope


def decompose(items, make, dt: float = 0.5, rot: int = 6):
    """総当たり表を作り、推移成分と巡回成分へ分ける。

    推移成分 r_i は「単にどれかが強い」分で、**値付けで消せる**。
    巡回成分 c は「本物の三すくみ」で、値付けでは動かない。
    分けずに見ていると、どちらが原因か区別できない。
    """
    slope = yardstick(dt)
    k = len(items)
    M = {}
    for i in range(k):
        M[(i, i)] = 0.0
        for j in range(i + 1, k):
            m = matchup_cost(make(items[i]), make(items[j]), slope, dt, rot)
            M[(i, j)] = m
            M[(j, i)] = -m
    rating = [sum(M[(i, j)] for j in range(k)) / k for i in range(k)]
    cyc = None
    if k == 3:
        cyc = (M[(0, 1)] + M[(1, 2)] + M[(2, 0)]) / 3.0
    return M, rating, cyc


def type_table(dt: float = 0.5, rot: int = 6):
    """3兵種の総当たり表と、その推移成分・巡回成分。"""
    return decompose((INF, CAV, ARC), type_army, dt, rot)


