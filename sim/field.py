# 武力と知力（§三国志らしさ）。
#
# **素の能力値は 武力 と 知力 で、攻撃力はそこからの導出値**にする。いまの能力値は
# 兵力・攻撃力・防御力・命中・クリ・速度 と全部が物理で、諸葛亮と呂布が同じ軸だけで
# 測られていた。攻撃力を導出にすると、兵種ごとに配合を変えられる。
#
#   攻撃力 = 武力 × (1 - w) + 知力 × w        w = INT_WEIGHT[兵種]
#
# 弓兵の w が高いのは、射撃が指揮と弾着の判断に効くため。近接は武力が主。
# **知力 = 武力 のとき導出値は武力に一致する**ので、合成カード（バランス測定用）は
# 影響を受けない。較正済みの係数はそのまま使える。
