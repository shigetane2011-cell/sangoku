def damage_ramp(t: float) -> float:
    if t <= RAMP_START:
        return 1.0
    f = (t - RAMP_START) / max(T_MAX - RAMP_START, 1e-9)
    return 1.0 + (RAMP_END_MULT - 1.0) * min(f, 1.0)


