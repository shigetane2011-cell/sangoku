def cmd_heal(args) -> None:
    """回復とダメージの交換レートを測る。

    **零点は「同じ技どうしで 0.00」。** 回復側とダメージ側で技が違うので、
    倍率を振って margin が 0 を切る点を探す。技が一度も撃たれない条件では
    どんな倍率でも差が出ないため、まず発動回数を出して計器を確かめる。
    """
    global HEAL_SCALE, ROUT_RATIO, SKILLS_ON
    keep_h, keep_r, keep_s = HEAL_SCALE, ROUT_RATIO, SKILLS_ON
    SKILLS_ON = True        # **これを忘れると全部 0.00 が並ぶ**（§13）

    def army(power, heal, typ=INF, gc=100.0):
        n = "＿測" + repr((power, heal, typ, gc))
        SKILL_INFO[n] = Skill(power, "melee", 0.0, heal)
        SKILL_TARGET[n] = "敵1体（最前）" if power > 0 else "味方1体（残兵力が最少）"
        return Army(tuple(Card(BASE_COST, typ, r, skill=n, gauge_cost=gc)
                          for r in MIXED_ROLES), FORM_STANDARD)

    def solve(typ=INF, gc=100.0, dt=1.0):
        # **nonlocal ではなく global。** ここを書き忘れると HEAL_SCALE が
        # solve のローカルになり、盤面へ伝わらないまま二分探索が端まで走る
        # （0.05 と 300.00 が並ぶ。実際に踏んだ）。
        global HEAL_SCALE
        lo, hi = 0.05, 300.0
        for _ in range(40):
            HEAL_SCALE = (lo + hi) / 2
            if simulate(army(0.0, 2.0, typ, gc), army(2.0, 0.0, typ, gc),
                        dt)["diff"] < 0:
                lo = HEAL_SCALE
            else:
                hi = HEAL_SCALE
        return (lo + hi) / 2

    print("回復とダメージの交換レート（ダメージ側は SKILL_SCALE = {:.1f}）".format(
        SKILL_SCALE))
    print()
    print("【計器】技が実際に撃たれているか。撃たれない条件では何を測っても嘘。")
    print("  {:<12}{:>14}".format("消費ゲージ", "1枚あたり発動"))
    for gc in (50.0, 100.0, 175.0, 250.0):
        a = army(2.0, 0.0, INF, gc)
        n = sum(x for _, x in simulate(a, a, 1.0)["fires_a"]) / 6.0
        print("  {:<12g}{:>14.2f}{}".format(
            gc, n, "   ★撃っていない" if n < 0.5 else ""))
    print()
    print("【本測定】回復がダメージと釣り合う倍率。")
    print("  {:<20}{:>12}{:>14}".format("条件", "必要倍率", "ダメージ比"))
    rows = []
    for lab, kw in (("歩兵", {}), ("騎兵", {"typ": CAV}), ("弓兵", {"typ": ARC}),
                    ("消費50（手数）", {"gc": 50.0}),
                    ("時間刻み0.25", {"dt": 0.25})):
        v = solve(**kw)
        rows.append(v)
        print("  {:<20}{:>12.2f}{:>13.2f}倍".format(lab, v, v / SKILL_SCALE))
    print()
    print("  帯 {:.2f}〜{:.2f}。採用値 HEAL_SCALE = {:.1f}".format(
        min(rows), max(rows), keep_h))
    print()
    print("  **回復のほうが強い。** 回復は防御力を通らない（減った兵を戻すだけで")
    print("  殴られてはいない）ぶん効率がよい。歩兵の防御{:.1f}なら {:.2f}倍。".format(
        DEF_BY_TYPE[INF], 1.0 + DEF_BY_TYPE[INF] / 100.0))
    print()
    print("【説明の検証】旧盤面の「回復はダメージの6倍」は決着条件の違いでは。")
    print("  決着が早いほどダメージの価値が上がるはず。潰走の閾値を振る。")
    print("  {:<14}{:>12}".format("潰走の閾値", "必要倍率"))
    for r in (0.20, 0.40, 0.60):
        ROUT_RATIO = r
        print("  {:<14.0%}{:>12.2f}".format(r, solve()))
    ROUT_RATIO, HEAL_SCALE, SKILLS_ON = keep_r, keep_h, keep_s
    print("  → 向きは合っているが、この盤面では効きが小さい（+11%）。")
    print("    旧盤面の6倍は総大将撤退が決着の88%だったからで、1枚落とせば")
    print("    即勝ちなら回復では買えない価値がダメージにあった。いまは無い。")


def cmd_dot(args) -> None:
    """継続ダメージが「総量が同じ打ち切り技」より弱いことを確かめる。"""
    global SKILLS_ON
    keep, SKILLS_ON = SKILLS_ON, True   # **これを忘れると全部 0.00 が並ぶ**（§13）

    def army(power, dur):
        n = "＿継" + repr((power, dur))
        SKILL_INFO[n] = Skill(power, "scheme", dur, 0.0)
        SKILL_TARGET[n] = "敵1列"
        return Army(tuple(Card(BASE_COST, INF, r, skill=n)
                          for r in MIXED_ROLES), FORM_STANDARD)
    print("継続ダメージ 対 打ち切り（総量は同じ）")
    print()
    print("  威力40% × 14秒 = 総量560% を、14秒かけて入れる場合と1発で入れる場合。")
    print("  取りこぼし（相手が先に潰走する・回復と競争する）のぶん継続が弱いはず。")
    print()
    print("  **総量を揃えること。** 継続側の威力は毎秒の量なので、打ち切り側は")
    print("  威力 × 秒数 にする。ここを揃え損ねると 14倍の差を測ることになる。")
    print()
    print("  {:<10}{:>14}{:>10}".format("時間刻み", "継続 - 打切", "勝敗"))
    cont, inst = army(0.40, 14.0), army(0.40 * 14.0, 0.0)
    for dt in (1.0, 0.5, 0.25, 0.125):
        d = simulate(cont, inst, dt)["diff"]
        print("  {:<10}{:>+14.4f}{:>10}".format(dt, d, "継続の勝ち" if d > 0 else "打切の勝ち"))
    print()
    print("  零点（同じ技どうし。0.00 でなければバグ）")
    for lab, a in (("継続", cont), ("打切", inst)):
        print("    {:<8}{:+.2f}".format(lab, margin(a, a, 1.0)))
    SKILLS_ON = keep


def cmd_traits(args) -> None:
    """固有特性の値段を測る（コスト点。1枚だけが持つ形）。

    **式を当てず、測った表をそのまま使う。** 誘発型の値段は「いつ発動したか」で
    決まり、発動時刻は条件ごとに違う。たとえば背水（攻撃力+25%・90秒）は式なら
    2.96 だが実測は 0.096 で、30倍ずれる。**残り時間が90秒も無い**うえ、発動する
    ころには本人が4割まで削れていて攻撃力を上げても乗る兵が居ないためである。
    15種しかない固定データに、発動時刻の模型を作るほうが割に合わない。

    新しい特性を足したら、このコマンドで測って `sim/design.py` の表へ書くこと。
    """
    global SKILLS_ON, TRAITS_ON, TRAIT_TRIGGER
    from . import rosterdata as R
    R.load_skills_into_field()
    n = R.load_traits_into_field()
    SKILLS_ON = TRAITS_ON = True
    dt = args.dt
    ys = cost_yardstick(dt)

    def army(trait):
        return Army(tuple(replace(_synth(BASE_COST, INF, r),
                                  trait=(trait if i == 0 else ""))
                          for i, r in enumerate(MIXED_ROLES)), FORM_STANDARD)

    base = army("")
    print("固有特性の値段（誘発型 {}種。単位はコスト点／総コスト30）".format(n))
    print()
    print("【計器】零点 {:+.4f}（同編成どうし。0 でなければバグ）".format(
        margin(base, base, dt) / ys))
    print("  誘発の閾値 {:.0%}。**ここを ROUT_UNIT({:.0%}) にすると7種が死ぬ**"
          .format(TRAIT_TRIGGER, ROUT_UNIT))
    print("  （釣り合った対戦では誰もそこまで落ちないので、味方/敵の潰走を条件に")
    print("   する特性が一度も発動しない。実測で全部 0.0000 が並んだ）。")
    print()
    print("  {:<10}{:<16}{:>6}{:>10}".format("特性", "条件", "上限", "値段"))
    out = {}
    for k, (cond, tgt, cap, sk, jp) in TRAITS.items():
        v = margin(army(k), base, dt) / ys
        out[k] = v
        print("  {:<10}{:<16}{:>6}{:>10.4f}{}".format(
            jp, cond, cap, v, "   ★ほぼ無価値" if abs(v) < 0.05 else ""))

    # 常在型。TRAITS には入らないので別に測る。
    print()
    print("  {:<10}{:<16}{:>6}{:>10}   常在型".format("特性", "内容", "", "値段"))
    front = Army(tuple(replace(_synth(BASE_COST, INF, r),
                               trait=("vanguard" if i == 0 else ""))
                       for i, r in enumerate(MIXED_ROLES)), FORM_STANDARD)
    v = margin(front, base, dt) / ys
    out["vanguard"] = v
    print("  {:<10}{:<16}{:>6}{:>10.4f}".format(
        "陣頭", "前衛の兵力+{:.1%}".format(VANGUARD_MEN), "", v))
    # 対勢力は「その勢力の敵」が要る。両軍に勢力を持たせて測る。
    wei = Army(tuple(replace(_synth(BASE_COST, INF, r), faction="魏")
                     for r in MIXED_ROLES), FORM_STANDARD)
    anti = Army(tuple(replace(_synth(BASE_COST, INF, r),
                              trait=("vs_wei" if i == 0 else ""), faction="蜀")
                      for i, r in enumerate(MIXED_ROLES)), FORM_STANDARD)
    plain = Army(tuple(replace(_synth(BASE_COST, INF, r), faction="蜀")
                       for r in MIXED_ROLES), FORM_STANDARD)
    v = (margin(anti, wei, dt) - margin(plain, wei, dt)) / ys
    for k in FACTION_OF:
        out[k] = v
    print("  {:<10}{:<16}{:>6}{:>10.4f}   （vs_wei/shu/go 共通）".format(
        "対勢力", "該当勢力へ+{:.0%}".format(VS_FACTION), "", v))

    print()
    print("  sim/design.py の TRAIT_PRICE へ貼る形:")
    print("    TRAIT_PRICE = {")
    for k, v in sorted(out.items(), key=lambda kv: -kv[1]):
        print("        {!r}: {:.4f},".format(k, max(v, 0.0)))
    print("    }")


